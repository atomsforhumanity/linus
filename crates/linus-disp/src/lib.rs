/// Highest derivative to compute.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Order {
    Energy,
    #[default]
    Gradient,
    Hessian,
}

/// Dispersion energy and derivatives.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct DispResult {
    /// Eh
    pub energy: f64,
    /// Eh/bohr, one entry per atom (empty for [`Order::Energy`])
    pub gradient: Vec<[f64; 3]>,
    /// Eh/bohr^2, row-major 3N x 3N (index `3 * atom + xyz`), for [`Order::Hessian`]
    pub hessian: Option<Vec<f64>>,
}

/// Errors of the dispersion corrections.
#[derive(Clone, Debug, PartialEq)]
pub enum DispError {
    /// Element outside the model's parametrization.
    UnsupportedElement {
        model: &'static str,
        atom: usize,
        number: u32,
    },
    /// No parameters for this functional.
    NoParameters {
        functional: String,
        model: &'static str,
        note: String,
    },
    /// Inconsistent input sizes.
    Shape(String),
    /// Numerical failure (singular EEQ matrix).
    Numerical(String),
}

impl std::fmt::Display for DispError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            DispError::UnsupportedElement {
                model,
                atom,
                number,
            } => {
                write!(f, "{model}: unsupported element Z={number} (atom {atom})")
            }
            DispError::NoParameters {
                functional,
                model,
                note,
            } => {
                write!(f, "no {model} parameters for functional '{functional}'")?;
                if !note.is_empty() {
                    write!(f, " ({note})")?;
                }
                Ok(())
            }
            DispError::Shape(s) => write!(f, "shape mismatch: {s}"),
            DispError::Numerical(s) => write!(f, "numerical failure: {s}"),
        }
    }
}

impl std::error::Error for DispError {}
