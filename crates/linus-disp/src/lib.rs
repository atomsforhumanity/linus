//! Dispersion corrections for linus: DFT-D3 with rational (Becke-Johnson) damping and the
//! optional ATM three-body term (port of s-dftd3 1.7.0), and DFT-D4 (axtb-d4, bit-identical
//! to dftd4 4.3.1, with EEQ 2019 charges ported from multicharge 0.6.0). Energies, analytic
//! gradients and analytic Hessians, molecules only.
//!
//! ```no_run
//! use linus_disp::*;
//! # let z = [8u32, 1, 1];
//! # let xyz = [[0.0f64; 3]; 3];
//! let p = d3bj_params("b3lyp")?;                      // ORCA B3LYP D3BJ (two-body)
//! let r = d3bj(&z, &xyz, &p, &D3Options { order: Order::Hessian, ..Default::default() })?;
//! let (e, g, h) = (r.energy, r.gradient, r.hessian.unwrap()); // Eh, Eh/bohr, Eh/bohr^2
//! let p4 = d4_params("r2scan-3c")?;
//! let r4 = d4(&z, &xyz, 0.0, &p4, &D4Options::default())?;  // total charge 0
//! # Ok::<(), DispError>(())
//! ```
//!
//! Units: bohr and Hartree. Every function runs on the current rayon pool (install a pool
//! to control the thread count); results are bitwise identical for any pool size.
//!
//! License: LGPL-3.0-or-later (this crate only; see README.md and NOTICE.md).

