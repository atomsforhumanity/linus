#!/usr/bin/env python
"""Generate src/element_data.rs (per-element radii / scaling tables).

Tables (all numerical data, i.e. published physical parameters):
  * BRAGG_ANGSTROM: Bragg-Slater radii (Angstrom) as tabulated in PySCF
    (pyscf.data.radii.BRAGG * BOHR); J.C. Slater, J. Chem. Phys. 41, 3199 (1964),
    with PySCF's choices for H (0.35 A), noble gases and heavy elements.
  * COVALENT_ANGSTROM: covalent radii (Cordero et al., Dalton Trans. 2008) as in PySCF.
  * SG1_RADII_BOHR: Gill-Johnson-Pople SG-1 atomic radii (CPL 209, 506 (1993)).
  * TREUTLER_XI: Treutler-Ahlrichs radial scaling xi (JCP 102, 346 (1995)) for H-Kr,
    extended to heavier elements with the values used by Psi4/PySCF.
  * PSI4_BS_RADII_BOHR: Bragg-Slater radii (bohr) used by Psi4 1.11 (libfock/cubature.cc)
    for its radial scaling and Becke/Treutler size adjustment (numbers only).
Usage: python tools/gen_element_tables.py [path/to/psi4/cubature.cc] > src/element_data.rs
"""
import re
import sys
import numpy as np
from pyscf.data import radii
from pyscf.lib.parameters import BOHR
from pyscf.dft import radi


def fmt(arr, per=8):
    lines = []
    for i in range(0, len(arr), per):
        lines.append("    " + ", ".join(repr(float(x)) for x in arr[i:i + per]) + ",")
    return "\n".join(lines)


def psi4_bs(path):
    src = open(path).read()
    m = re.search(r"double GetBSRadius\(unsigned Z\) \{.*?BSRadius ?=\{(.*?)\};", src, re.S)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    return [float(x) for x in re.findall(r"[0-9]+\.[0-9]+", body)]


def main():
    bragg_ang = np.array(radii.BRAGG) * BOHR
    # recover the exact decimal inputs (PySCF stores 1/BOHR * value)
    bragg_ang = np.round(bragg_ang, 6)
    cov_ang = np.round(np.array(radii.COVALENT) * BOHR, 6)
    assert np.allclose((1 / BOHR) * bragg_ang, radii.BRAGG, rtol=0, atol=0), "inexact Bragg roundtrip"
    assert np.allclose((1 / BOHR) * cov_ang, radii.COVALENT, rtol=0, atol=0), "inexact covalent roundtrip"
    out = ["// @generated by tools/gen_element_tables.py -- do not edit by hand.",
           "// See the generator for the provenance of each table.", ""]
    out.append(f"/// Bragg-Slater radii in Angstrom as tabulated by PySCF; index = Z (0 = ghost).")
    out.append(f"pub static BRAGG_ANGSTROM: [f64; {len(bragg_ang)}] = [\n{fmt(bragg_ang)}\n];")
    out.append(f"/// Covalent radii in Angstrom as tabulated by PySCF; index = Z (0 = ghost).")
    out.append(f"pub static COVALENT_ANGSTROM: [f64; {len(cov_ang)}] = [\n{fmt(cov_ang)}\n];")
    sg1 = np.array(radi.SG1RADII)
    out.append(f"/// SG-1 atomic radii in bohr (Gill, Johnson, Pople 1993); index = Z, H-Ar.")
    out.append(f"pub static SG1_RADII_BOHR: [f64; {len(sg1)}] = [\n{fmt(sg1)}\n];")
    xi = np.array(radi._treutler_ahlrichs_xi)
    out.append(f"/// Treutler-Ahlrichs radial scaling parameters xi; index = Z (0 = ghost).")
    out.append(f"pub static TREUTLER_XI: [f64; {len(xi)}] = [\n{fmt(xi)}\n];")
    if len(sys.argv) > 1:
        bs = psi4_bs(sys.argv[1])
        out.append(f"/// Bragg-Slater radii in bohr as used by Psi4 1.11 (index = Z; 0 = ghost; 3.30 beyond).")
        out.append(f"pub static PSI4_BS_RADII_BOHR: [f64; {len(bs)}] = [\n{fmt(bs)}\n];")
    print("\n".join(out))


if __name__ == "__main__":
    main()
