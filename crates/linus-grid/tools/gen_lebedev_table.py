#!/usr/bin/env python
"""Generate src/lebedev_data.rs from a permissively licensed Lebedev-Laikov source.

Source: ``scipy/integrate/_lebedev.py`` (SciPy >= 1.15, BSD-3-Clause), which is a
translation of Robert Parrish's ``getLebedevSphere`` (BSD-2-Clause, (c) 2010 Robert
Parrish), itself translated from Christoph van Wuellen's Fortran version of Dmitri
Laikov's C routines. The numbers are the published Lebedev-Laikov generator
parameters [V.I. Lebedev, D.N. Laikov, Doklady Mathematics 59, 477-481 (1999) and
earlier papers by Lebedev].  Only the orbit generators (orbit type, a, b, v) are
extracted; the points are generated in Rust from the Oh symmetry orbits.

The script optionally cross-checks the extracted generators against PySCF's
``pyscf/dft/LebedevGrid.py`` (independent transcription of the same tables) and
reports any difference.

Usage:  python tools/gen_lebedev_table.py > src/lebedev_data.rs
"""
import re
import sys
import importlib.util
import inspect


def parse_scipy():
    import scipy.integrate._lebedev as m
    src = inspect.getsource(m.get_lebedev_sphere)
    tables = {}
    cur = None
    a = b = v = None
    for line in src.splitlines():
        s = line.strip()
        mm = re.match(r"case (\d+):", s)
        if mm:
            cur = int(mm.group(1))
            tables[cur] = []
            a = b = v = None
            continue
        mm = re.match(r"([abv]) = ([-+0-9.eE]+)$", s)
        if mm and cur is not None:
            if mm.group(1) == 'a':
                a = mm.group(2)
            elif mm.group(1) == 'b':
                b = mm.group(2)
            else:
                v = mm.group(2)
            continue
        mm = re.match(r"leb_tmp, start = get_lebedev_recurrence_points\((\d), start, a, b, v, leb_tmp\)", s)
        if mm and cur is not None:
            t = int(mm.group(1))
            aa = a if t in (4, 5, 6) else "0.0"
            bb = b if t == 6 else "0.0"
            tables[cur].append((t, aa, bb, v))
    return tables, m.__file__, __import__('scipy').__version__


def parse_pyscf():
    try:
        import pyscf.dft.LebedevGrid as m
    except Exception:
        return None
    src = open(m.__file__).read()
    tables = {}
    for mm in re.finditer(r"def MakeAngularGrid_(\d+)\(\):(.*?)return np.vstack", src, re.S):
        n = int(mm.group(1))
        body = mm.group(2)
        a = b = v = None
        lst = []
        for line in body.splitlines():
            s = line.strip()
            m2 = re.match(r"([abv]) = ([-+0-9.eE]+)$", s)
            if m2:
                if m2.group(1) == 'a':
                    a = m2.group(2)
                elif m2.group(1) == 'b':
                    b = m2.group(2)
                else:
                    v = m2.group(2)
            m2 = re.match(r"grids.append\(SphGenOh\((\d), a, b, v\)\)", s)
            if m2:
                t = int(m2.group(1)) + 1
                lst.append((t, a if t in (4, 5, 6) else "0.0", b if t == 6 else "0.0", v))
        tables[n] = lst
    return tables


def main():
    tables, path, ver = parse_scipy()
    npts = {1: 6, 2: 12, 3: 8, 4: 24, 5: 24, 6: 48}
    for n, lst in tables.items():
        assert sum(npts[t] for t, *_ in lst) == n, n
    py = parse_pyscf()
    ndiff = 0
    if py is not None:
        for n, lst in tables.items():
            other = py.get(n)
            if other is None:
                print(f"// pyscf lacks {n}", file=sys.stderr)
                continue
            if len(other) != len(lst):
                print(f"// orbit count differs for {n}", file=sys.stderr)
                ndiff += 1
                continue
            # compare as floats, orbit order may differ -> compare sorted
            k1 = sorted((t, float(a), float(b), float(v)) for t, a, b, v in lst)
            k2 = sorted((t, float(a), float(b), float(v)) for t, a, b, v in other)
            for x, y in zip(k1, k2):
                if x != y:
                    ndiff += 1
                    print(f"// {n}: scipy {x} pyscf {y}", file=sys.stderr)
        print(f"cross-check vs pyscf: {ndiff} differing generators", file=sys.stderr)

