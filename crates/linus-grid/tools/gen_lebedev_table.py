    out.append("")
    out.append("/// (number of points, algebraic degree of exactness, orbits)")
    out.append("pub(crate) static LEBEDEV_TABLE: &[(usize, usize, &[Orbit])] = &[")
    degree = {6: 3, 14: 5, 26: 7, 38: 9, 50: 11, 74: 13, 86: 15, 110: 17, 146: 19, 170: 21, 194: 23,
              230: 25, 266: 27, 302: 29, 350: 31, 434: 35, 590: 41, 770: 47, 974: 53, 1202: 59,
              1454: 65, 1730: 71, 2030: 77, 2354: 83, 2702: 89, 3074: 95, 3470: 101, 3890: 107,
              4334: 113, 4802: 119, 5294: 125, 5810: 131}
    for n in sorted(tables):
        out.append(f"    ({n}, {degree[n]}, &[")
        for t, a, b, v in tables[n]:
            def f(x):
                x = x.replace('E', 'e')
                return x if ('.' in x or 'e' in x) else x + '.0'
            out.append(f"        ({t}, {f(a)}, {f(b)}, {f(v)}),")
        out.append("    ]),")
    out.append("];")
    print("\n".join(out))


