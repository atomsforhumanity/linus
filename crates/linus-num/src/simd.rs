#[cfg(target_arch = "x86_64")]
pub use avx2::Avx2;

#[cfg(target_arch = "x86_64")]
mod avx2 {
    use super::*;
    use core::arch::x86_64::*;

    /// Two `__m256d` (lanes 0-3, 4-7). Internal to linus (not public API): its methods execute
    /// AVX2/FMA instructions. Only construct inside functions compiled with
    /// `#[target_feature(enable = "avx2,fma")]` after run-time detection. (Explicit
    /// intrinsics: `[f64; 8]` loops make LLVM re-vectorize every operation, which is slow to
    /// compile for the large generated kernels.)
    #[doc(hidden)]
    #[derive(Clone, Copy, Debug)]
    pub struct Avx2(pub __m256d, pub __m256d);

    macro_rules! avx2_binop {
        ($tr:ident, $f:ident, $intr:ident, $tra:ident, $fa:ident) => {
            impl $tr for Avx2 {
                type Output = Self;
                #[inline(always)]
                fn $f(self, o: Self) -> Self {
                    unsafe { Avx2($intr(self.0, o.0), $intr(self.1, o.1)) }
                }
            }
            impl $tra for Avx2 {
                #[inline(always)]
                fn $fa(&mut self, o: Self) {
                    *self = unsafe { Avx2($intr(self.0, o.0), $intr(self.1, o.1)) };
                }
            }
        };
    }
    avx2_binop!(Add, add, _mm256_add_pd, AddAssign, add_assign);
    avx2_binop!(Sub, sub, _mm256_sub_pd, SubAssign, sub_assign);
    avx2_binop!(Mul, mul, _mm256_mul_pd, MulAssign, mul_assign);

    impl Div for Avx2 {
        type Output = Self;
        #[inline(always)]
        fn div(self, o: Self) -> Self {
            unsafe { Avx2(_mm256_div_pd(self.0, o.0), _mm256_div_pd(self.1, o.1)) }
        }
    }

    impl Neg for Avx2 {
        type Output = Self;
        #[inline(always)]
        fn neg(self) -> Self {
            unsafe {
                let z = _mm256_setzero_pd();
                Avx2(_mm256_sub_pd(z, self.0), _mm256_sub_pd(z, self.1))
            }
        }
    }

    impl Real for Avx2 {
        #[inline(always)]
        fn splat(x: f64) -> Self {
            unsafe { Avx2(_mm256_set1_pd(x), _mm256_set1_pd(x)) }
        }
        #[inline(always)]
        fn mul_add(self, b: Self, c: Self) -> Self {
            unsafe {
                Avx2(
                    _mm256_fmadd_pd(self.0, b.0, c.0),
                    _mm256_fmadd_pd(self.1, b.1, c.1),
                )
            }
        }
        #[inline(always)]
        fn sqrt(self) -> Self {
            unsafe { Avx2(_mm256_sqrt_pd(self.0), _mm256_sqrt_pd(self.1)) }
        }
    }

    /// Integer-valued doubles 0 <= x < 2^52 to i64 lanes (exact).
    #[inline(always)]
    unsafe fn to_i64(x: __m256d) -> __m256i {
        const MAGIC: f64 = 4_503_599_627_370_496.0; // 2^52
        let m = _mm256_set1_pd(MAGIC);
        _mm256_sub_epi64(
            _mm256_castpd_si256(_mm256_add_pd(x, m)),
            _mm256_castpd_si256(m),
        )
    }

    impl Lanes for Avx2 {
        type Idx = (__m256i, __m256i);
        #[inline(always)]
        fn load(s: &[f64]) -> Self {
            assert!(s.len() >= LANES);
            unsafe {
                Avx2(
                    _mm256_loadu_pd(s.as_ptr()),
                    _mm256_loadu_pd(s.as_ptr().add(4)),
                )
            }
        }
        #[inline(always)]
        fn load8(a: &[f64; LANES]) -> Self {
            unsafe {
                Avx2(
                    _mm256_loadu_pd(a.as_ptr()),
                    _mm256_loadu_pd(a.as_ptr().add(4)),
                )
            }
        }
        #[inline(always)]
        fn store(self, s: &mut [f64]) {
            assert!(s.len() >= LANES);
            unsafe {
                _mm256_storeu_pd(s.as_mut_ptr(), self.0);
                _mm256_storeu_pd(s.as_mut_ptr().add(4), self.1);
            }
        }
        #[inline(always)]
        fn from_array(a: [f64; LANES]) -> Self {
            Self::load8(&a)
        }
        #[inline(always)]
        fn to_array(self) -> [f64; LANES] {
            let mut a = [0.0; LANES];
            self.store(&mut a);
            a
        }
        #[inline(always)]
        fn round(self) -> Self {
            const R: i32 = _MM_FROUND_TO_NEAREST_INT | _MM_FROUND_NO_EXC;
            unsafe { Avx2(_mm256_round_pd::<R>(self.0), _mm256_round_pd::<R>(self.1)) }
        }
        #[inline(always)]
        fn min(self, o: Self) -> Self {
            unsafe { Avx2(_mm256_min_pd(self.0, o.0), _mm256_min_pd(self.1, o.1)) }
        }
        #[inline(always)]
        fn max(self, o: Self) -> Self {
            unsafe { Avx2(_mm256_max_pd(self.0, o.0), _mm256_max_pd(self.1, o.1)) }
        }
        #[inline(always)]
        fn abs(self) -> Self {
            unsafe {
                let m = _mm256_set1_pd(-0.0);
                Avx2(_mm256_andnot_pd(m, self.0), _mm256_andnot_pd(m, self.1))
            }
        }
        #[inline(always)]
        fn lt(self, o: Self) -> u8 {
            unsafe {
                let a = _mm256_movemask_pd(_mm256_cmp_pd::<_CMP_LT_OQ>(self.0, o.0)) as u8;
                let b = _mm256_movemask_pd(_mm256_cmp_pd::<_CMP_LT_OQ>(self.1, o.1)) as u8;
                a | (b << 4)
            }
        }
        #[inline(always)]
        fn select(mask: u8, a: Self, b: Self) -> Self {
            unsafe {
                let bits = _mm256_set_epi64x(8, 4, 2, 1);
                let m0 = _mm256_set1_epi64x((mask & 15) as i64);
                let m1 = _mm256_set1_epi64x((mask >> 4) as i64);
                let s0 = _mm256_castsi256_pd(_mm256_cmpeq_epi64(_mm256_and_si256(m0, bits), bits));
                let s1 = _mm256_castsi256_pd(_mm256_cmpeq_epi64(_mm256_and_si256(m1, bits), bits));
                Avx2(
                    _mm256_blendv_pd(b.0, a.0, s0),
                    _mm256_blendv_pd(b.1, a.1, s1),
                )
            }
        }
        #[inline(always)]
        fn scale2(self, n: Self) -> Self {
            // 2^n from the exponent bits: (n + 1023) << 52
            unsafe {
                let o = _mm256_set1_pd(1023.0);
                let e0 = _mm256_slli_epi64::<52>(to_i64(_mm256_add_pd(n.0, o)));
                let e1 = _mm256_slli_epi64::<52>(to_i64(_mm256_add_pd(n.1, o)));
                Avx2(
                    _mm256_mul_pd(self.0, _mm256_castsi256_pd(e0)),
                    _mm256_mul_pd(self.1, _mm256_castsi256_pd(e1)),
                )
            }
        }
        #[inline(always)]
        fn index(row: Self, stride: usize) -> Self::Idx {
            unsafe {
                let s = _mm256_set1_pd(stride as f64);
                (
                    to_i64(_mm256_mul_pd(row.0, s)),
                    to_i64(_mm256_mul_pd(row.1, s)),
                )
            }
        }
        #[inline(always)]
        fn make_idx(a: [usize; LANES]) -> Self::Idx {
            unsafe {
                (
                    _mm256_loadu_si256(a.as_ptr() as *const __m256i),
                    _mm256_loadu_si256(a.as_ptr().add(4) as *const __m256i),
                )
            }
        }
        #[inline(always)]
        unsafe fn gather(table: &[f64], idx: Self::Idx, offset: usize) -> Self {
            unsafe {
                let base = table.as_ptr().add(offset);
                Avx2(
                    _mm256_i64gather_pd::<8>(base, idx.0),
                    _mm256_i64gather_pd::<8>(base, idx.1),
                )
            }
        }
        #[inline(always)]
        unsafe fn gather_rows8(table: &[f64], row: Self, stride: usize, col: usize) -> [Self; 8] {
            // eight row loads and an 8x8 transpose (the default's gathers ran through a
            // closure compiled without AVX2)
            unsafe {
                let ri = row.to_array();
                let base = table.as_ptr().add(col);
                let mut r = [Avx2(_mm256_setzero_pd(), _mm256_setzero_pd()); 8];
                for l in 0..LANES {
                    let p = base.add(ri[l] as usize * stride);
                    r[l] = Avx2(_mm256_loadu_pd(p), _mm256_loadu_pd(p.add(4)));
                }
                Self::transpose8(r)
            }
        }
        #[inline(always)]
        unsafe fn load_rows4(base: *const f64, offs: &[usize; LANES]) -> [Self; 4] {
            #[inline(always)]
            unsafe fn t4(a: __m256d, b: __m256d, c: __m256d, d: __m256d) -> [__m256d; 4] {
                let t0 = _mm256_unpacklo_pd(a, b);
                let t1 = _mm256_unpackhi_pd(a, b);
                let t2 = _mm256_unpacklo_pd(c, d);
                let t3 = _mm256_unpackhi_pd(c, d);
                [
                    _mm256_permute2f128_pd::<0x20>(t0, t2),
                    _mm256_permute2f128_pd::<0x20>(t1, t3),
                    _mm256_permute2f128_pd::<0x31>(t0, t2),
                    _mm256_permute2f128_pd::<0x31>(t1, t3),
                ]
            }
            let lo = t4(
                _mm256_loadu_pd(base.add(offs[0])),
                _mm256_loadu_pd(base.add(offs[1])),
                _mm256_loadu_pd(base.add(offs[2])),
                _mm256_loadu_pd(base.add(offs[3])),
            );
            let hi = t4(
                _mm256_loadu_pd(base.add(offs[4])),
                _mm256_loadu_pd(base.add(offs[5])),
                _mm256_loadu_pd(base.add(offs[6])),
                _mm256_loadu_pd(base.add(offs[7])),
            );
            [
                Avx2(lo[0], hi[0]),
                Avx2(lo[1], hi[1]),
                Avx2(lo[2], hi[2]),
                Avx2(lo[3], hi[3]),
            ]
        }
        #[inline(always)]
        fn transpose8(v: [Self; 8]) -> [Self; 8] {
            #[inline(always)]
            unsafe fn t4(a: __m256d, b: __m256d, c: __m256d, d: __m256d) -> [__m256d; 4] {
                let t0 = _mm256_unpacklo_pd(a, b);
                let t1 = _mm256_unpackhi_pd(a, b);
                let t2 = _mm256_unpacklo_pd(c, d);
                let t3 = _mm256_unpackhi_pd(c, d);
                [
                    _mm256_permute2f128_pd::<0x20>(t0, t2),
                    _mm256_permute2f128_pd::<0x20>(t1, t3),
                    _mm256_permute2f128_pd::<0x31>(t0, t2),
                    _mm256_permute2f128_pd::<0x31>(t1, t3),
                ]
            }
            unsafe {
                // rows 0-3 / 4-7 (v index) x lanes 0-3 / 4-7 (halves)
                let a = t4(v[0].0, v[1].0, v[2].0, v[3].0);
                let b = t4(v[4].0, v[5].0, v[6].0, v[7].0);
                let c = t4(v[0].1, v[1].1, v[2].1, v[3].1);
                let d = t4(v[4].1, v[5].1, v[6].1, v[7].1);
                [
                    Avx2(a[0], b[0]),
                    Avx2(a[1], b[1]),
                    Avx2(a[2], b[2]),
                    Avx2(a[3], b[3]),
                    Avx2(c[0], d[0]),
                    Avx2(c[1], d[1]),
                    Avx2(c[2], d[2]),
                    Avx2(c[3], d[3]),
                ]
            }
        }
        #[inline(always)]
        unsafe fn add_to8(self, dst: *mut f64) {
            _mm256_storeu_pd(dst, _mm256_add_pd(_mm256_loadu_pd(dst), self.0));
            _mm256_storeu_pd(
                dst.add(4),
                _mm256_add_pd(_mm256_loadu_pd(dst.add(4)), self.1),
            );
        }
        #[inline(always)]
        unsafe fn add_to_low<const N: usize>(self, dst: *mut f64) {
            match N {
                4 => _mm256_storeu_pd(dst, _mm256_add_pd(_mm256_loadu_pd(dst), self.0)),
                2 => _mm_storeu_pd(
                    dst,
                    _mm_add_pd(_mm_loadu_pd(dst), _mm256_castpd256_pd128(self.0)),
                ),
                1 => *dst += _mm256_cvtsd_f64(self.0),
                _ => unreachable!(),
            }
        }
        #[inline(always)]
        fn hsum(self) -> f64 {
            // same pairwise order as Avx512::hsum and Portable::hsum
            unsafe {
                let s4 = _mm256_add_pd(self.0, self.1);
                let a = _mm256_castpd256_pd128(s4);
                let b = _mm256_extractf128_pd::<1>(s4);
                let s2 = _mm_add_pd(a, b);
                let h = _mm_unpackhi_pd(s2, s2);
                _mm_cvtsd_f64(_mm_add_sd(s2, h))
            }
        }
    }
}

