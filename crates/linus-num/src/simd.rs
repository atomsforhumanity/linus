//! The SIMD layer of the workspace: lane-parallel f64 arithmetic and the run-time choice of the
//! instruction set.
//!
//! Kernels are written once, generic over [`Real`] (plain arithmetic, used by generated code)
//! or [`Lanes`] (8 lanes plus the extra operations the Boys function and data movement need).
//! Implementations:
//! - `f64`: one lane (scalar reference path);
//! - [`Avx512`]: one `__m512d` (x86-64 with AVX-512F/DQ, selected at run time);
//! - [`Portable<FMA>`]: `[f64; 8]`, which LLVM vectorizes for whatever features the calling
//!   function enables (AVX2+FMA with `FMA = true`, baseline SSE2 with `FMA = false`).
//!
//! Every batched kernel is instantiated for each type behind a `#[target_feature]` entry
//! point and chosen once per process at run time ([`Isa::detect`], lowered by `LINUS_ISA`), so
//! one binary runs everywhere. Code with its own entry points gates them on the same
//! [`Isa::detect`]: written by hand, or generated by [`multiversion!`](crate::multiversion)
//! (one body compiled per instruction set) and
//! [`multiversion_lanes!`](crate::multiversion_lanes) (a body generic over its lane count,
//! instantiated wider for AVX-512).

use std::ops::{Add, AddAssign, Div, Mul, MulAssign, Neg, Sub, SubAssign};

/// Lane count of the batched kernels (fixed by the data layout, independent of the ISA).
pub const LANES: usize = 8;

/// Plain floating-point arithmetic (what generated straight-line code uses).
pub trait Real:
    Copy
    + Send
    + Sync
    + Add<Output = Self>
    + Sub<Output = Self>
    + Mul<Output = Self>
    + Div<Output = Self>
    + Neg<Output = Self>
    + AddAssign
    + SubAssign
    + MulAssign
{
    fn splat(x: f64) -> Self;
    #[inline(always)]
    fn zero() -> Self {
        Self::splat(0.0)
    }
    /// self * b + c (fused where the ISA has FMA)
    fn mul_add(self, b: Self, c: Self) -> Self;
    fn sqrt(self) -> Self;
}

impl Real for f64 {
    #[inline(always)]
    fn splat(x: f64) -> Self {
        x
    }
    #[inline(always)]
    fn mul_add(self, b: Self, c: Self) -> Self {
        self * b + c
    }
    #[inline(always)]
    fn sqrt(self) -> Self {
        f64::sqrt(self)
    }
}

/// Eight lanes with the operations needed beyond arithmetic.
pub trait Lanes: Real {
    /// Integer index vector for gathers.
    type Idx: Copy;
    fn load(s: &[f64]) -> Self;
    /// Load from a fixed-size array (no bounds check).
    fn load8(a: &[f64; LANES]) -> Self;
    fn store(self, s: &mut [f64]);
    fn from_array(a: [f64; LANES]) -> Self;
    fn to_array(self) -> [f64; LANES];
    /// Round to nearest integer (ties to even).
    fn round(self) -> Self;
    fn min(self, o: Self) -> Self;
    fn max(self, o: Self) -> Self;
    fn abs(self) -> Self;
    /// Bit i set where self\[i\] < o\[i\].
    fn lt(self, o: Self) -> u8;
    /// Lane i from a where bit i of mask is set, else from b.
    fn select(mask: u8, a: Self, b: Self) -> Self;
    /// self * 2^n for integer-valued n (n >= -1022).
    fn scale2(self, n: Self) -> Self;
    /// Index vector row * stride for integer-valued non-negative `row`.
    fn index(row: Self, stride: usize) -> Self::Idx;
    /// Index vector from per-lane offsets.
    fn make_idx(a: [usize; LANES]) -> Self::Idx;
    /// table\[idx\[i\] + offset\] (unchecked).
    /// # Safety
    /// idx\[i\] + offset < table.len() for every lane.
    unsafe fn gather(table: &[f64], idx: Self::Idx, offset: usize) -> Self;
    /// out\[k\]\[lane\] = table\[row\[lane\] * stride + col + k\], k = 0..8 (eight consecutive
    /// entries of one table row per lane; unchecked).
    /// # Safety
    /// Every `row` lane is a non-negative integer and row * stride + col + 8 <= table.len().
    #[inline(always)]
    unsafe fn gather_rows8(table: &[f64], row: Self, stride: usize, col: usize) -> [Self; 8] {
        let idx = Self::index(row, stride);
        std::array::from_fn(|k| Self::gather(table, idx, col + k))
    }
    /// out\[k\] lane l = base[offs\[l\] + k] for k < 8: eight consecutive values per lane,
    /// transposed (lane-major rows to one vector per row).
    /// # Safety
    /// base + offs\[l\] must be valid for 8 reads for every lane.
    #[inline(always)]
    unsafe fn load_rows8(base: *const f64, offs: &[usize; LANES]) -> [Self; 8] {
        let mut r = [Self::zero(); 8];
        for (l, x) in r.iter_mut().enumerate() {
            *x = Self::load8(&*(base.add(offs[l]) as *const [f64; LANES]));
        }
        Self::transpose8(r)
    }
    /// out\[k\] lane l = base[offs\[l\] + k] for k < 4.
    /// # Safety
    /// base + offs\[l\] must be valid for 4 reads for every lane.
    #[inline(always)]
    unsafe fn load_rows4(base: *const f64, offs: &[usize; LANES]) -> [Self; 4] {
        let mut a = [[0.0f64; LANES]; 4];
        for l in 0..LANES {
            for (k, row) in a.iter_mut().enumerate() {
                row[l] = *base.add(offs[l] + k);
            }
        }
        [
            Self::from_array(a[0]),
            Self::from_array(a[1]),
            Self::from_array(a[2]),
            Self::from_array(a[3]),
        ]
    }
    /// Sum of the lanes.
    fn hsum(self) -> f64;
    /// 8 x 8 transpose: out\[l\] lane j = v\[j\] lane l.
    #[inline(always)]
    fn transpose8(v: [Self; 8]) -> [Self; 8] {
        let a = v.map(|x| x.to_array());
        std::array::from_fn(|l| Self::from_array(std::array::from_fn(|j| a[j][l])))
    }
    /// dst\[i\] += self lane i for i < n (n <= LANES).
    /// # Safety
    /// `dst` must be valid for n reads and writes.
    #[inline(always)]
    unsafe fn add_to(self, dst: *mut f64, n: usize) {
        let a = self.to_array();
        for (i, &x) in a.iter().enumerate().take(n) {
            *dst.add(i) += x;
        }
    }
    /// dst\[i\] += self lane i for i < LANES (unmasked; same sums as `add_to(dst, LANES)`).
    /// # Safety
    /// `dst` must be valid for LANES reads and writes.
    #[inline(always)]
    unsafe fn add_to8(self, dst: *mut f64) {
        let a = self.to_array();
        for (i, &x) in a.iter().enumerate() {
            *dst.add(i) += x;
        }
    }
    /// dst\[i\] += self lane i for i < N, N = 1, 2 or 4 (the low lanes, unmasked loads and
    /// stores of that width; same sums as `add_to(dst, N)`).
    /// # Safety
    /// `dst` must be valid for N reads and writes.
    #[inline(always)]
    unsafe fn add_to_low<const N: usize>(self, dst: *mut f64) {
        let a = self.to_array();
        for (i, &x) in a.iter().enumerate().take(N) {
            *dst.add(i) += x;
        }
    }
    /// Split into 128-bit fixed point with 2^-64 resolution: x = hi + lo * 2^-64 with
    /// hi = floor(x) and 0 <= lo < 2^64 (truncated; saturating at the top).
    #[inline(always)]
    fn fixed_split(self, hi: &mut [i64; LANES], lo: &mut [u64; LANES]) {
        const TWO64: f64 = 18_446_744_073_709_551_616.0;
        let a = self.to_array();
        for i in 0..LANES {
            let h = a[i].floor();
            hi[i] = h as i64;
            lo[i] = ((a[i] - h) * TWO64) as u64;
        }
    }
    /// 128-bit fixed-point accumulation per lane: (hi\[l\] 2^64 + lo\[l\]) += the fixed-point
    /// value of lane l ([`Lanes::fixed_split`]), exact (two's complement, wrapping).
    /// # Safety
    /// `hi` and `lo` must be valid for reads and writes.
    #[inline(always)]
    unsafe fn fixed_add(self, hi: *mut [i64; LANES], lo: *mut [u64; LANES]) {
        let mut h = [0i64; LANES];
        let mut l = [0u64; LANES];
        self.fixed_split(&mut h, &mut l);
        let (hi, lo) = (&mut *hi, &mut *lo);
        for i in 0..LANES {
            let v = (((hi[i] as i128) << 64) | lo[i] as i128)
                .wrapping_add(((h[i] as i128) << 64) + l[i] as i128);
            hi[i] = (v >> 64) as i64;
            lo[i] = v as u64;
        }
    }
}

// ------------------------------------------------------------------ portable

/// `[f64; 8]` lanes; `FMA` selects fused multiply-add (only use with FMA hardware enabled).
#[derive(Clone, Copy, Debug)]
#[repr(C, align(64))]
pub struct Portable<const FMA: bool>(pub [f64; LANES]);

macro_rules! portable_binop {
    ($tr:ident, $f:ident, $op:tt, $tra:ident, $fa:ident) => {
        impl<const FMA: bool> $tr for Portable<FMA> {
            type Output = Self;
            #[inline(always)]
            fn $f(self, o: Self) -> Self {
                let mut r = [0.0; LANES];
                for i in 0..LANES {
                    r[i] = self.0[i] $op o.0[i];
                }
                Portable(r)
            }
        }
        impl<const FMA: bool> $tra for Portable<FMA> {
            #[inline(always)]
            fn $fa(&mut self, o: Self) {
                *self = *self $op o;
            }
        }
    };
}
portable_binop!(Add, add, +, AddAssign, add_assign);
portable_binop!(Sub, sub, -, SubAssign, sub_assign);
portable_binop!(Mul, mul, *, MulAssign, mul_assign);

impl<const FMA: bool> Div for Portable<FMA> {
    type Output = Self;
    #[inline(always)]
    #[allow(clippy::needless_range_loop, reason = "indexes several arrays in step")]
    fn div(self, o: Self) -> Self {
        let mut r = [0.0; LANES];
        for i in 0..LANES {
            r[i] = self.0[i] / o.0[i];
        }
        Portable(r)
    }
}

impl<const FMA: bool> Neg for Portable<FMA> {
    type Output = Self;
    #[inline(always)]
    #[allow(clippy::needless_range_loop, reason = "indexes several arrays in step")]
    fn neg(self) -> Self {
        let mut r = [0.0; LANES];
        for i in 0..LANES {
            r[i] = -self.0[i];
        }
        Portable(r)
    }
}

impl<const FMA: bool> Real for Portable<FMA> {
    #[inline(always)]
    fn splat(x: f64) -> Self {
        Portable([x; LANES])
    }
    #[inline(always)]
    #[allow(clippy::needless_range_loop, reason = "indexes several arrays in step")]
    fn mul_add(self, b: Self, c: Self) -> Self {
        let mut r = [0.0; LANES];
        for i in 0..LANES {
            r[i] = if FMA {
                self.0[i].mul_add(b.0[i], c.0[i])
            } else {
                self.0[i] * b.0[i] + c.0[i]
            };
        }
        Portable(r)
    }
    #[inline(always)]
    #[allow(clippy::needless_range_loop, reason = "indexes several arrays in step")]
    fn sqrt(self) -> Self {
        let mut r = [0.0; LANES];
        for i in 0..LANES {
            r[i] = self.0[i].sqrt();
        }
        Portable(r)
    }
}

impl<const FMA: bool> Lanes for Portable<FMA> {
    type Idx = [usize; LANES];
    #[inline(always)]
    fn load(s: &[f64]) -> Self {
        Portable(s[..LANES].try_into().unwrap())
    }
    #[inline(always)]
    fn load8(a: &[f64; LANES]) -> Self {
        Portable(*a)
    }
    #[inline(always)]
    fn store(self, s: &mut [f64]) {
        s[..LANES].copy_from_slice(&self.0);
    }
    #[inline(always)]
    fn from_array(a: [f64; LANES]) -> Self {
        Portable(a)
    }
    #[inline(always)]
    fn to_array(self) -> [f64; LANES] {
        self.0
    }
    #[inline(always)]
    #[allow(clippy::needless_range_loop, reason = "indexes several arrays in step")]
    fn round(self) -> Self {
        let mut r = [0.0; LANES];
        for i in 0..LANES {
            r[i] = self.0[i].round_ties_even();
        }
        Portable(r)
    }
    #[inline(always)]
    #[allow(clippy::needless_range_loop, reason = "indexes several arrays in step")]
    fn min(self, o: Self) -> Self {
        let mut r = [0.0; LANES];
        for i in 0..LANES {
            r[i] = if self.0[i] < o.0[i] {
                self.0[i]
            } else {
                o.0[i]
            };
        }
        Portable(r)
    }
    #[inline(always)]
    #[allow(clippy::needless_range_loop, reason = "indexes several arrays in step")]
    fn max(self, o: Self) -> Self {
        let mut r = [0.0; LANES];
        for i in 0..LANES {
            r[i] = if self.0[i] > o.0[i] {
                self.0[i]
            } else {
                o.0[i]
            };
        }
        Portable(r)
    }
    #[inline(always)]
    #[allow(clippy::needless_range_loop, reason = "indexes several arrays in step")]
    fn abs(self) -> Self {
        let mut r = [0.0; LANES];
        for i in 0..LANES {
            r[i] = self.0[i].abs();
        }
        Portable(r)
    }
    #[inline(always)]
    fn lt(self, o: Self) -> u8 {
        let mut m = 0u8;
        for i in 0..LANES {
            m |= ((self.0[i] < o.0[i]) as u8) << i;
        }
        m
    }
    #[inline(always)]
    #[allow(clippy::needless_range_loop, reason = "indexes several arrays in step")]
    fn select(mask: u8, a: Self, b: Self) -> Self {
        let mut r = [0.0; LANES];
        for i in 0..LANES {
            r[i] = if mask >> i & 1 == 1 { a.0[i] } else { b.0[i] };
        }
        Portable(r)
    }
    #[inline(always)]
    #[allow(clippy::needless_range_loop, reason = "indexes several arrays in step")]
    fn scale2(self, n: Self) -> Self {
        let mut r = [0.0; LANES];
        for i in 0..LANES {
            r[i] = self.0[i] * f64::from_bits(((n.0[i] as i64 + 1023) as u64) << 52);
        }
        Portable(r)
    }
    #[inline(always)]
    #[allow(clippy::needless_range_loop, reason = "indexes several arrays in step")]
    fn index(row: Self, stride: usize) -> Self::Idx {
        let mut r = [0usize; LANES];
        for i in 0..LANES {
            r[i] = row.0[i] as usize * stride;
        }
        r
    }
    #[inline(always)]
    fn make_idx(a: [usize; LANES]) -> Self::Idx {
        a
    }
    #[inline(always)]
    unsafe fn gather(table: &[f64], idx: Self::Idx, offset: usize) -> Self {
        let mut r = [0.0; LANES];
        for i in 0..LANES {
            r[i] = table[idx[i] + offset];
        }
        Portable(r)
    }
    #[inline(always)]
    fn hsum(self) -> f64 {
        let a = self.0;
        ((a[0] + a[4]) + (a[2] + a[6])) + ((a[1] + a[5]) + (a[3] + a[7]))
    }
}

