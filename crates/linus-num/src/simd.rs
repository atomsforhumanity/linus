/// Instruction set of the run-time dispatched code: `Avx512` runs entry points compiled with
/// `#[target_feature(enable = "avx512f,avx512dq,avx512vl,avx2,fma")]` (or a subset), `Avx2`
/// those with `"avx2,fma"`, `Generic` the baseline code.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Isa {
    Avx512,
    Avx2,
    Generic,
}

impl Isa {
    /// The instruction set of every dispatched kernel, decided once per process: the best the
    /// CPU supports ([`Isa::hardware`]), or the one named by `LINUS_ISA` (`generic`, `avx2`,
    /// `avx512`; for tests and comparisons) when the CPU can run it; an override above what the
    /// CPU supports falls back to the CPU's best, an unknown value is ignored (with a warning).
    #[inline]
    pub fn detect() -> Isa {
        static I: std::sync::OnceLock<Isa> = std::sync::OnceLock::new();
        *I.get_or_init(|| {
            Self::select(std::env::var("LINUS_ISA").ok().as_deref(), Self::hardware())
        })
    }

    /// The best instruction set of this CPU: AVX-512 needs F, DQ and VL (with AVX2 and FMA),
    /// AVX2 needs FMA too (the features the dispatched code enables).
    pub fn hardware() -> Isa {
        #[cfg(target_arch = "x86_64")]
        {
            let avx2 =
                std::is_x86_feature_detected!("avx2") && std::is_x86_feature_detected!("fma");
            if avx2
                && std::is_x86_feature_detected!("avx512f")
                && std::is_x86_feature_detected!("avx512dq")
                && std::is_x86_feature_detected!("avx512vl")
            {
                return Isa::Avx512;
            }
            if avx2 {
                return Isa::Avx2;
            }
        }
        Isa::Generic
    }

    /// `self`, or the CPU's best instruction set ([`Isa::hardware`]) if `self` is beyond it.
    pub fn clamped(self) -> Isa {
        let hw = Self::hardware();
        if self.rank() > hw.rank() {
            hw
        } else {
            self
        }
    }

    fn rank(self) -> u8 {
        match self {
            Isa::Generic => 0,
            Isa::Avx2 => 1,
            Isa::Avx512 => 2,
        }
    }

    /// The override `var` (LINUS_ISA) on a CPU whose best instruction set is `hw`.
    fn select(var: Option<&str>, hw: Isa) -> Isa {
        let want = match var.map(|v| v.trim().to_ascii_lowercase()).as_deref() {
            None | Some("") => return hw,
            Some("generic") => Isa::Generic,
            Some("avx2") => Isa::Avx2,
            Some("avx512") => Isa::Avx512,
            Some(v) => {
                // the form of every ignored switch (linus-ints `core::switches::ignore_invalid`);
                // once per process, as Isa::detect selects once
                eprintln!("linus: ignoring LINUS_ISA={v:?} (use generic, avx2 or avx512)");
                return hw;
            }
        };
        if want.rank() > hw.rank() {
            eprintln!("linus: LINUS_ISA={want:?} is not supported by this CPU; using {hw:?}");
            return hw;
        }
        want
    }
}

/// Defines `pub(crate) fn $name(args) -> $r` that runs `$body` (an `#[inline(always)]`
/// function with the same signature) compiled for AVX-512, AVX2 + FMA or the baseline, as
/// [`Isa::detect`] says. `pub fn ...` defines a public function (an entry point of the
/// crate's API); doc comments and attributes before `fn` go onto the function.
#[macro_export]
macro_rules! multiversion {
    ($(#[$m:meta])* pub fn $name:ident($($a:ident: $t:ty),* $(,)?) -> $r:ty = $body:ident) => {
        $(#[$m])*
        #[allow(clippy::too_many_arguments)]
        pub fn $name($($a: $t),*) -> $r {
            $crate::multiversion!(@dispatch $body($($a: $t),*) -> $r)
        }
    };
    ($(#[$m:meta])* fn $name:ident($($a:ident: $t:ty),* $(,)?) -> $r:ty = $body:ident) => {
        $(#[$m])*
        #[allow(clippy::too_many_arguments)]
        pub(crate) fn $name($($a: $t),*) -> $r {
            $crate::multiversion!(@dispatch $body($($a: $t),*) -> $r)
        }
    };
    (@dispatch $body:ident($($a:ident: $t:ty),*) -> $r:ty) => {{
            #[cfg(target_arch = "x86_64")]
            {
                #[target_feature(enable = "avx512f,avx512dq,avx512vl,avx2,fma")]
                #[allow(clippy::too_many_arguments)]
                unsafe fn v512($($a: $t),*) -> $r {
                    $body($($a),*)
                }
                #[target_feature(enable = "avx2,fma")]
                #[allow(clippy::too_many_arguments)]
                unsafe fn v256($($a: $t),*) -> $r {
                    $body($($a),*)
                }
                match $crate::simd::Isa::detect() {
                    // SAFETY: Isa::detect checked these features at run time
                    $crate::simd::Isa::Avx512 => return unsafe { v512($($a),*) },
                    $crate::simd::Isa::Avx2 => return unsafe { v256($($a),*) },
                    $crate::simd::Isa::Generic => {}
                }
            }
            $body($($a),*)
    }};
}

/// [`multiversion!`] for a body generic over its lane type: `= body::<A | B | C>` runs
/// `body::<A>` compiled for AVX-512, `body::<B>` for AVX2 + FMA and `body::<C>` on the baseline
/// (the [`Lanes`] types `Avx512`, `Avx2` and `Portable<false>`), as [`Isa::detect`] says.
/// `pub fn ...` defines a public function.
#[macro_export]
macro_rules! multiversion_typed {
    ($(#[$m:meta])* pub fn $name:ident($($a:ident: $t:ty),* $(,)?) -> $r:ty
        = $body:ident::<$w:ty | $n:ty | $g:ty>) => {
        $(#[$m])*
        #[allow(clippy::too_many_arguments)]
        pub fn $name($($a: $t),*) -> $r {
            $crate::multiversion_typed!(@dispatch $body::<$w | $n | $g>($($a: $t),*) -> $r)
        }
    };
    ($(#[$m:meta])* fn $name:ident($($a:ident: $t:ty),* $(,)?) -> $r:ty
        = $body:ident::<$w:ty | $n:ty | $g:ty>) => {
        $(#[$m])*
        #[allow(clippy::too_many_arguments)]
        pub(crate) fn $name($($a: $t),*) -> $r {
            $crate::multiversion_typed!(@dispatch $body::<$w | $n | $g>($($a: $t),*) -> $r)
        }
    };
    (@dispatch $body:ident::<$w:ty | $n:ty | $g:ty>($($a:ident: $t:ty),*) -> $r:ty) => {{
        #[cfg(target_arch = "x86_64")]
        {
            #[target_feature(enable = "avx512f,avx512dq,avx512vl,avx2,fma")]
            #[allow(clippy::too_many_arguments)]
            unsafe fn v512($($a: $t),*) -> $r {
                $body::<$w>($($a),*)
            }
            #[target_feature(enable = "avx2,fma")]
            #[allow(clippy::too_many_arguments)]
            unsafe fn v256($($a: $t),*) -> $r {
                $body::<$n>($($a),*)
            }
            match $crate::simd::Isa::detect() {
                // SAFETY: Isa::detect checked these features at run time
                $crate::simd::Isa::Avx512 => return unsafe { v512($($a),*) },
                $crate::simd::Isa::Avx2 => return unsafe { v256($($a),*) },
                $crate::simd::Isa::Generic => {}
            }
        }
        $body::<$g>($($a),*)
    }};
}

/// [`multiversion!`] for a body generic over its lane count (const generic parameters):
/// `= body::<16 | 8>` compiles `body::<16>` for AVX-512 and `body::<8>` for AVX2 + FMA and the
/// baseline; several parameters are listed in order on each side (`= block::<8, 4 | 4, 2>`).
/// Wider lanes keep more independent accumulators in AVX-512's 32 vector registers.
#[macro_export]
macro_rules! multiversion_lanes {
    (fn $name:ident($($a:ident: $t:ty),* $(,)?) -> $r:ty
        = $body:ident::<$($wide:tt),+ | $($narrow:tt),+>) => {
        #[allow(clippy::too_many_arguments)]
        pub(crate) fn $name($($a: $t),*) -> $r {
            #[cfg(target_arch = "x86_64")]
            {
                #[target_feature(enable = "avx512f,avx512dq,avx512vl,avx2,fma")]
                #[allow(clippy::too_many_arguments)]
                unsafe fn v512($($a: $t),*) -> $r {
                    $body::<$($wide),+>($($a),*)
                }
                #[target_feature(enable = "avx2,fma")]
                #[allow(clippy::too_many_arguments)]
                unsafe fn v256($($a: $t),*) -> $r {
                    $body::<$($narrow),+>($($a),*)
                }
                match $crate::simd::Isa::detect() {
                    // SAFETY: Isa::detect checked these features at run time
                    $crate::simd::Isa::Avx512 => return unsafe { v512($($a),*) },
                    $crate::simd::Isa::Avx2 => return unsafe { v256($($a),*) },
                    $crate::simd::Isa::Generic => {}
                }
            }
            $body::<$($narrow),+>($($a),*)
        }
    };
}

