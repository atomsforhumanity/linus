/// exp(x) for x <= 0 (x below -708 is clamped; the result there is below 1e-307).
/// Cody-Waite reduction by ln 2 and a degree-13 Taylor polynomial: < 2 ulp.
#[inline(always)]
pub fn exp_nonpos<V: Lanes>(x: V) -> V {
    const LOG2E: f64 = std::f64::consts::LOG2_E;
    // the digits of the Cody-Waite split as published (they round to the same f64)
    #[allow(clippy::excessive_precision)]
    const LN2_HI: f64 = 6.931_471_803_691_238_164_90e-01;
    #[allow(clippy::excessive_precision)]
    const LN2_LO: f64 = 1.908_214_929_270_587_700_02e-10;
    let x = x.max(V::splat(-708.0));
    let n = (x * V::splat(LOG2E)).round();
    let r = n.mul_add(V::splat(-LN2_HI), x);
    let r = n.mul_add(V::splat(-LN2_LO), r);
    // Taylor coefficients 1/k!, k = 13..0
    const C: [f64; 14] = [
        1.0 / 6_227_020_800.0,
        1.0 / 479_001_600.0,
        1.0 / 39_916_800.0,
        1.0 / 3_628_800.0,
        1.0 / 362_880.0,
        1.0 / 40_320.0,
        1.0 / 5_040.0,
        1.0 / 720.0,
        1.0 / 120.0,
        1.0 / 24.0,
        1.0 / 6.0,
        0.5,
        1.0,
        1.0,
    ];
    let mut p = V::splat(C[0]);
    for &c in &C[1..] {
        p = p.mul_add(r, V::splat(c));
    }
    p.scale2(n)
}

