//! Polarizable-continuum (PCM) surface terms on the device: the integrals of the cavity's surface
//! charges with the orbital pairs ([`PcmIntsHost`], `GpuPcmInts`) and the dense charge solve
//! (`GpuPcmSolver`, [`solver`]), the device counterparts of linus's CPU `solvent` module
//! (`pcm_ints::SurfacePlan`, `PcmOperator`).
//!
//! **Integrals.** Surface point g carries a normalized Gaussian charge of exponent zeta_g^2 (or a
//! point charge, zeta infinite: the `orca` preset). With D a symmetric density and q charges:
//! - the potential of D at the points, v_g = sum_mn D_mn (mn|g);
//! - the potential matrix of q, V_mn = sum_g q_g (mn|g);
//! - the gradient of sum_g q_g sum_mn D_mn (mn|g): the shell-centre part per atom and the point
//!   part per point (linus-ints' `pcm_ints::SurfaceDerivPlan::gradient`).
//!
//! The kernels are generated by tools/intgen (cuda_pcm.py, [`crate::kernels::pcm_gen`]): one
//! thread per pair primitive of Hermite degree L = la + lb loops over a chunk of the points
//! (shared-memory tiles; the chunks are a second grid dimension, sized here so that every
//! degree's launch fills the device), with Boys, the R recursion and the contraction in the
//! pair's Hermite space, as linus-ints' McMurchie-Davidson reference
//! `reference::pcm::potential_points`. Per primitive the
//! Hermite density h_t = sum_mn E\[mn\]\[t\] w_mn (w the pair-weighted density) is formed first
//! and the charges' accumulators A_t = sum_g q_g R_t(g) are contracted with E afterwards
//! (table-driven support kernels over the E nonzeros of tools/intgen's patterns), so the
//! potential and the matrix take one pass together (the fused pass of the `predicted` SCF mode).
//! The potential's sum over primitives is a fixed-order reduction per block and then over blocks
//! (TeraChem's "MS-driven" kernel, Liu et al., J. Chem. Theory Comput. 11, 3131 (2015)); the
//! gradient's atom sums use [`crate::detsum`]. Every result is bitwise reproducible run to run.
//!
//! Pairs: the shell pairs whose Schwarz bound times the largest sqrt((g|g)) (twice) reaches
//! `pair_thresh` (all of them for point charges), as linus-ints' `SurfacePlan` keeps them, and every
//! primitive pair above linus-ints' `PRIM_PAIR_CUT`; no density screening (the device computes
//! what the CPU would screen away below its integral threshold).

