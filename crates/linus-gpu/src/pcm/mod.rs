/// A surface point as the solute's potential sees it: a normalized Gaussian charge of exponent
/// zeta^2 at `r` (bohr), or a point charge (`zeta` infinite).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct PcmPoint {
    pub r: [f64; 3],
    pub zeta: f64,
}

impl PcmPoint {
    /// sqrt((g|g)) = (zeta sqrt(2/pi))^1/2 (infinite for a point charge).
    fn sqrt_self(&self) -> f64 {
        (self.zeta * (2.0 / std::f64::consts::PI).sqrt()).sqrt()
    }
}

/// The pair data of one orbital class (l1 >= l2, kernel order) for the support kernels.
#[derive(Clone, Debug, Default)]
pub struct PcmClass {
    pub l1: usize,
    pub l2: usize,
    /// First primitive of the class in the list of its Hermite degree l1 + l2.
    pub deg_off: usize,
    /// Per pair: AO offsets of the kernel's first and second shell, diagonal flag (the same
    /// shell twice), the shells' atoms.
    pub pairs: Vec<i32>,
    /// Primitive offsets per pair (npair + 1), class-local.
    pub p0: Vec<i32>,
    /// The pair of each primitive.
    pub prim_pair: Vec<i32>,
    /// Per primitive the E nonzeros in pattern order (`e_pattern(l1, l2, None)`).
    pub e: Vec<f64>,
    /// Per primitive the nonzeros of the six derivative expansions d/dA x, y, z, d/dB x, y, z
    /// (A the first shell's centre), each in pattern order (derivative packing only).
    pub d: Vec<f64>,
    /// CSR by Hermite index: hp (nherm + 1), the nonzero's record offset and mn.
    pub hp: Vec<i32>,
    pub he: Vec<i32>,
    pub hm: Vec<i32>,
    /// CSR by function pair mn: ep (nab + 1), record offset and Hermite index.
    pub ep: Vec<i32>,
    pub ee: Vec<i32>,
    pub er: Vec<i32>,
    /// The derivative nonzeros: set starts (7), Hermite index and mn per nonzero.
    pub gs: Vec<i32>,
    pub gr: Vec<i32>,
    pub gm: Vec<i32>,
}

impl PcmClass {
    pub fn npair(&self) -> usize {
        self.p0.len().saturating_sub(1)
    }

    pub fn nprim(&self) -> usize {
        self.prim_pair.len()
    }

    pub fn degree(&self) -> usize {
        self.l1 + self.l2
    }

    pub fn nab(&self) -> usize {
        nfunc(self.l1) * nfunc(self.l2)
    }

    /// E nonzeros per primitive.
    pub fn nnz(&self) -> usize {
        self.he.len()
    }

    /// Derivative nonzeros per primitive.
    pub fn nnz_d(&self) -> usize {
        self.gr.len()
    }
}

/// The packed host data of the surface integrals (see the module docs): no GPU needed.
#[derive(Clone, Debug)]
pub struct PcmIntsHost {
    pub nbf: usize,
    pub natom: usize,
    pub npts: usize,
    /// Per point: x, y, z, zeta^2, zeta (zeta^2 = zeta = 0 for a point charge).
    pub points: Vec<f64>,
    /// Per Hermite degree L = 0..=MAX_L: the primitives' p, Px, Py, Pz.
    pub prims: Vec<Vec<f64>>,
    /// Classes (l1 >= l2) with pairs.
    pub classes: Vec<PcmClass>,
    pub derivatives: bool,
    /// Shell pairs of the basis, and those kept by the Schwarz screen.
    pub npairs: usize,
    pub npairs_kept: usize,
}

impl PcmIntsHost {
    /// Packs the shell pairs of `basis` that pass the screen (module docs) against `points`;
    /// with `derivatives`, also the data of the gradient. CPU work runs on the current rayon
    /// pool.
    pub fn new(
        basis: &BasisSet,
        points: &[PcmPoint],
        pair_thresh: f64,
        derivatives: bool,
    ) -> Result<PcmIntsHost, GpuError> {
        Self::with_pairs(basis, None, points, pair_thresh, derivatives)
    }

    /// [`PcmIntsHost::new`] screening the shell pairs of `pairs` (the index-ordered pairs of
    /// `basis` that a caller already built, of any derivative order: their Schwarz factors are
    /// the same, [`PairSet::is_default_set_of`]) instead of building them; None, or a set of
    /// another kind, size or primitive cut: built here.
    pub fn with_pairs(
        basis: &BasisSet,
        pairs: Option<&PairSet>,
        points: &[PcmPoint],
        pair_thresh: f64,
        derivatives: bool,
    ) -> Result<PcmIntsHost, GpuError> {
        for s in &basis.shells {
            if s.l >= 2 && !s.pure {
                return Err(GpuError::NotCovered(format!(
                    "PCM: Cartesian l = {} shells are not supported by the device kernels",
                    s.l
                )));
            }
            if s.l > 4 {
                return Err(GpuError::NotCovered(format!(
                    "PCM: l = {} is beyond the device kernels (l <= 4)",
                    s.l
                )));
            }
        }
        let gmax = points.iter().map(|p| p.sqrt_self()).fold(0.0, f64::max);
        let built;
        let pl = match pairs.filter(|p| p.is_default_set_of(basis)) {
            Some(p) => p,
            None => {
                built = PairSet::build(basis, PairOptions::default());
                &built
            }
        };
        let q = pl.schwarz();
        let kept: Vec<usize> = (0..pl.len())
            .filter(|&k| pl.pair(k).nprim > 0 && q[k] * gmax * 2.0 >= pair_thresh)
            .collect();
        let views: Vec<ShellView> = basis.shells.iter().map(ShellView::from_shell).collect();
        // per kept pair, in kernel order (higher l first): the class, its pair record and the
        // primitives' data
        struct Built {
            ci: usize,
            info: [i32; 5],
            prims: Vec<[f64; 4]>,
            e: Vec<f64>,
            d: Vec<f64>,
        }
        let cidx = |l1: usize, l2: usize| l1 * (l1 + 1) / 2 + l2;
        let pats: Vec<Vec<(usize, usize)>> = (0..=4)
            .flat_map(|l1| (0..=l1).map(move |l2| (l1, l2)))
            .map(|(l1, l2)| e_pattern(l1, l2, None))
            .collect();
        let dpats: Vec<Vec<Vec<(usize, usize)>>> = (0..=4)
            .flat_map(|l1| (0..=l1).map(move |l2| (l1, l2)))
            .map(|(l1, l2)| {
                if derivatives {
                    (0..6)
                        .map(|s| e_pattern(l1, l2, Some((s / 3, s % 3))))
                        .collect()
                } else {
                    Vec::new()
                }
            })
            .collect();
        let sh = &basis.shells;
        let built: Vec<Built> = kept
            .par_iter()
            .filter_map(|&k| {
                let pr = pl.pair(k);
                let (s1, s2) = if sh[pr.sa].l >= sh[pr.sb].l {
                    (pr.sa, pr.sb)
                } else {
                    (pr.sb, pr.sa)
                };
                let (l1, l2) = (sh[s1].l, sh[s2].l);
                // E, and E^A for the derivatives, from the one primitive loop
                let order = if derivatives { 1 } else { 0 };
                let (sp, pd) =
                    pair_data::build(&views[s1], &views[s2], s1, s2, order, PRIM_PAIR_CUT);
                if sp.nprim == 0 {
                    return None;
                }
                let ci = cidx(l1, l2);
                let nab = sp.nab();
                let pat = &pats[ci];
                let mut e = Vec::with_capacity(sp.nprim * pat.len());
                let mut prims = Vec::with_capacity(sp.nprim);
                for ip in 0..sp.nprim {
                    prims.push([sp.p[ip], sp.pc[ip][0], sp.pc[ip][1], sp.pc[ip][2]]);
                    let ep = sp.e_prim(ip);
                    e.extend(pat.iter().map(|&(r, mn)| ep[r * nab + mn]));
                }
                let mut d = Vec::new();
                if derivatives {
                    let pd = pd.expect("first-order pair data");
                    let nh1 = nherm(l1 + l2 + 1);
                    let mut eb = vec![0.0; nh1 * 3 * nab];
                    for ip in 0..sp.nprim {
                        let ea = pd.ea_prim(ip);
                        eb_prim(&sp, &pd, ip, &mut eb);
                        for (s, set) in dpats[ci].iter().enumerate() {
                            let (src, x) = if s < 3 { (ea, s) } else { (&eb[..], s - 3) };
                            d.extend(set.iter().map(|&(r, mn)| src[(r * 3 + x) * nab + mn]));
                        }
                    }
                }
                Some(Built {
                    ci,
                    info: [
                        sh[s1].ao_start as i32,
                        sh[s2].ao_start as i32,
                        (s1 == s2) as i32,
                        sh[s1].atom as i32,
                        sh[s2].atom as i32,
                    ],
                    prims,
                    e,
                    d,
                })
            })
            .collect();
        // classes with their tables
        let mut classes: Vec<PcmClass> = (0..=4)
            .flat_map(|l1| (0..=l1).map(move |l2| (l1, l2)))
            .map(|(l1, l2)| {
                let ci = cidx(l1, l2);
                let pat = &pats[ci];
                let nh = nherm(l1 + l2);
                let nab = nfunc(l1) * nfunc(l2);
                let mut c = PcmClass {
                    l1,
                    l2,
                    p0: vec![0],
                    ..Default::default()
                };
                // by Hermite index (the patterns are sorted by (r, mn))
                c.hp = vec![0; nh + 1];
                for (j, &(r, mn)) in pat.iter().enumerate() {
                    c.hp[r + 1] += 1;
                    c.he.push(j as i32);
                    c.hm.push(mn as i32);
                }
                for r in 0..nh {
                    c.hp[r + 1] += c.hp[r];
                }
                // by function pair
                c.ep = vec![0; nab + 1];
                let mut by_mn: Vec<(usize, usize, usize)> = pat
                    .iter()
                    .enumerate()
                    .map(|(j, &(r, mn))| (mn, r, j))
                    .collect();
                by_mn.sort();
                for &(mn, r, j) in &by_mn {
                    c.ep[mn + 1] += 1;
                    c.ee.push(j as i32);
                    c.er.push(r as i32);
                }
                for x in 0..nab {
                    c.ep[x + 1] += c.ep[x];
                }
                if derivatives {
                    c.gs.push(0);
                    for set in &dpats[ci] {
                        for &(r, mn) in set {
                            c.gr.push(r as i32);
                            c.gm.push(mn as i32);
                        }
                        c.gs.push(c.gr.len() as i32);
                    }
                }
                c
            })
            .collect();
        let mut prims: Vec<Vec<f64>> = vec![Vec::new(); MAX_L + 1];
        for b in &built {
            let c = &mut classes[b.ci];
            let pair = c.npair() as i32;
            c.pairs.extend_from_slice(&b.info);
            c.prim_pair.extend(std::iter::repeat_n(pair, b.prims.len()));
            c.p0.push(c.prim_pair.len() as i32);
            c.e.extend_from_slice(&b.e);
            c.d.extend_from_slice(&b.d);
        }
        // the degree lists: classes of one degree back to back, in class order, each class's
        // primitives in pair order
        let mut per_class: Vec<Vec<f64>> = vec![Vec::new(); classes.len()];
        for b in &built {
            for p in &b.prims {
                per_class[b.ci].extend_from_slice(p);
            }
        }
        for (ci, c) in classes.iter_mut().enumerate() {
            let l = c.degree();
            c.deg_off = prims[l].len() / 4;
            prims[l].extend_from_slice(&per_class[ci]);
        }
        let mut pts = Vec::with_capacity(5 * points.len());
        for p in points {
            let (z2, z) = if p.zeta.is_finite() {
                (p.zeta * p.zeta, p.zeta)
            } else {
                (0.0, 0.0)
            };
            pts.extend_from_slice(&[p.r[0], p.r[1], p.r[2], z2, z]);
        }
        let natom = basis
            .shells
            .iter()
            .map(|s| s.atom + 1)
            .max()
            .unwrap_or(0)
            .max(basis.atom_shells.len());
        Ok(PcmIntsHost {
            nbf: basis.nbf,
            natom,
            npts: points.len(),
            points: pts,
            prims,
            classes,
            derivatives,
            npairs: pl.len(),
            npairs_kept: built.len(),
        })
    }

    /// Primitives of Hermite degree `l`.
    pub fn nprim(&self, l: usize) -> usize {
        self.prims[l].len() / 4
    }

    /// Thread blocks of the main kernels over all degrees (rows of the partial sums).
    pub fn nblocks(&self) -> usize {
        let t = crate::kernels::pcm_gen::THREADS as usize;
        (0..=MAX_L).map(|l| self.nprim(l).div_ceil(t)).sum()
    }
}

