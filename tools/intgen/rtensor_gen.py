"""Rust emitter (layer c), part 1: the Rust expression printer shared by the Rust emitters, and
crates/linus-ints/src/generated/rtensor.rs, the straight-line Hermite Coulomb integrals R_tuv
(t + u + v <= L) for L = 0..R_MAX_L from R^(n)_000, generic over `V: Real`.

The R recursion is mdmath.r_recursion with the schedule's direction rule, as an ir.Graph; every R
value is bound to a `let` (registers), emitted level by level from n = L down.
"""
from ir import RUST, Graph, r_graph
from mdmath import herm_tuv, nherm

HEADER = """// @generated by tools/intgen/intgen.py -- do not edit by hand.
#![allow(clippy::all)]
"""


class RustPrinter:
    """Prints ir.Graph nodes as Rust over `V: Real`: a * b, a.mul_add(b, c), a + b, constants as
    V::splat(c). Nodes bound to a name (a `let`) print as that name; others inline. A receiver of a
    method call that starts with a dereference is parenthesized."""

    def __init__(self):
        self.names = {}

    def bind(self, node, name):
        self.names[node.id] = name

    def ref(self, n):
        name = self.names.get(n.id)
        return name if name is not None else self.defn(n)

    def recv(self, n):
        s = self.ref(n)
        return f"({s})" if s.startswith("*") else s

    def defn(self, n):
        if n.op == "in":
            return n.value
        if n.op == "const":
            return f"V::splat({n.value!r})"
        a = n.args
        if n.op == "mul":
            return f"{self.ref(a[0])} * {self.ref(a[1])}"
        if n.op == "add":
            return f"{self.ref(a[0])} + {self.ref(a[1])}"
        if n.op == "fma":
            return f"{self.recv(a[0])}.mul_add({self.ref(a[1])}, {self.ref(a[2])})"
        raise ValueError(n.op)


def r_lets(L, rule, indent="    "):
    """The straight-line R recursion as `let` statements, and the printer that names the values.
    Returns (lines, printer, nodes) with nodes[(0, t, u, v)] the level-0 values."""
    g = Graph()
    _, nodes = r_graph(g, L, rule, lambda n: g.inp(f"rn[{n}]"), [g.inp("x"), g.inp("y"), g.inp("z")])
    pr = RustPrinter()
    lines = []
    for (n, t, u, v), node in nodes.items():
        lines.append(f"{indent}let r{n}_{t}_{u}_{v} = {pr.defn(node)};")
        pr.bind(node, f"r{n}_{t}_{u}_{v}")
    return lines, pr, nodes


def gen_rtensor(L, sched=RUST):
    """Straight-line R_tuv for t+u+v <= L."""
    body, pr, nodes = r_lets(L, sched.r_rule)
    for k, (t, u, v) in enumerate(herm_tuv(L)):
        body.append(f"    out[{k}] = {pr.ref(nodes[(0, t, u, v)])};")
    lines = [f"/// R_tuv for t+u+v <= {L} (Hermite order) from rn[n] = R^(n)_000, n = 0..={L}.",
             "#[inline(always)]",
             "#[allow(unused_variables)]",
             f"pub fn r_tensor_{L}<V: Real>(rn: &[V], x: V, y: V, z: V, out: &mut [V]) {{",
             f"    let (rn, out) = (&rn[..{L + 1}], &mut out[..{nherm(L)}]);"]
    lines.extend(body)
    lines.append("}")
    return "\n".join(lines)


def generate(sched=RUST):
    R_MAX_L = sched.r_max_l
    parts = [HEADER, "use linus_num::simd::Real;\n", f"pub const R_MAX_L: usize = {R_MAX_L};\n"]
    for L in range(R_MAX_L + 1):
        parts.append(gen_rtensor(L, sched))
        parts.append("")
    parts.append("""/// Dispatch to the unrolled R_tuv for L <= R_MAX_L; returns false for larger L.
#[inline(always)]
pub fn r_tensor_unrolled<V: Real>(l: usize, rn: &[V], x: V, y: V, z: V, out: &mut [V]) -> bool {
    match l {""")
    for L in range(R_MAX_L + 1):
        parts.append(f"        {L} => r_tensor_{L}(rn, x, y, z, out),")
    parts.append("""        _ => return false,
    }
    true
}
""")
    # per-ISA entry points (each with its own target features, not inlined into callers)
    parts.append("""/// Defines `#[target_feature]` wrappers `r_tensor_0..` for one lane type and the table
/// `R_TENSOR_FNS` (index L). Use inside a module: `r_tensor_isa_fns!(Avx512, "avx512f,...");`
#[macro_export]
macro_rules! r_tensor_isa_fns {
    ($V:ty $(, $feat:literal)?) => {""")
    for L in range(R_MAX_L + 1):
        parts.append(f"        $(#[target_feature(enable = $feat)])? pub unsafe fn r_tensor_{L}(rn: &[$V], x: $V, y: $V, z: $V, out: &mut [$V]) {{ $crate::generated::rtensor::r_tensor_{L}(rn, x, y, z, out) }}")
    names = ", ".join(f"r_tensor_{L}" for L in range(R_MAX_L + 1))
    parts.append(f"        pub static R_TENSOR_FNS: [unsafe fn(&[$V], $V, $V, $V, &mut [$V]); {R_MAX_L + 1}] = [{names}];")
    parts.append("""    };
}
""")
    return "\n".join(parts)
