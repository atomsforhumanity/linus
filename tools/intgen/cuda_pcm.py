"""CUDA emitter (layer c): integrals of polarizable-continuum surface charges for linus-gpu's PCM
engine (crates/linus-gpu/src/pcm), McMurchie-Davidson as linus-ints' points::pcm_ints.

Surface point g carries a normalized Gaussian charge (zeta_g^2 / pi)^{3/2} exp(-zeta_g^2 r^2), or a
point charge (zeta infinite; the `orca` preset). Its Coulomb integral with an orbital pair is the
three-center integral (mn|P) of the generated eri3c kernels with an s-type auxiliary function of
exponent zeta^2, scaled to unit charge: for a pair primitive (exponent p, centre P)

    (Lambda_t | g) = (2 pi / p) sqrt(alpha / p) R_t(alpha, P - r_g),  alpha = p zeta^2 / (p + zeta^2),

(alpha = p for a point charge), so only the Boys stage differs from eri3c's s-type class, and
there is no auxiliary contraction: the kernels work in the Hermite space of the pair, as the
J-engine-like CPU reference does. Per pair primitive the host side supplies the Hermite density
h_t = sum_mn E[mn][t] w_mn (w_mn the pair-weighted density block, from the E nonzeros of the
eri3c records) and contracts the accumulated A_t afterwards; these kernels do the work that
scales with primitives x points:

- `pcm_e{L}`, L = la + lb (0..8): a grid of (blocks of pair primitives of degree L, one thread
  each) x (chunks of points); a thread loops over its chunk's points in shared-memory tiles.
  Per (primitive, point): Boys F_0..F_L, the R recursion (straight-line, every index of degree
  <= L), and
  - with `want_v`: v = sum_t h_t R_t, the primitive's share of the potential of the density at the
    point. The block sums its threads' shares per point in a fixed order (a shuffle tree per warp,
    then the warps in order) and writes one partial per (block, point) to `vpart` (TeraChem's
    "MS-driven" reduction, Liu et al. JCTC 11, 3131 (2015)); a second kernel sums the partials
    over the blocks in a fixed order;
  - with `want_m`: A_t += q_g R_t in registers (the charges' potential matrix in Hermite space,
    V_mn = sum_prim sum_t E[mn][t] A_t), one partial per (primitive, chunk), summed over the
    chunks in a fixed order by the host side.
  Both in one pass is the fused pass of the `predicted` SCF mode. The point chunks keep the card
  busy when a degree has few primitives (the host chooses the chunk size per launch).
- `pcm_d{L}`: the first derivatives for the gradient, on the same grid. R up to degree L + 1;
  per point c_k = sum_t h_t R_{t + e_k} (the derivative of the potential with respect to the
  point, -d/dC; reduced over the block's threads per point as above, three partials per point),
  and A_t += q_g R_t over degree L + 1 per (primitive, chunk) (contracted by the host side with
  the derivative expansions d/dA and d/dB of the pair, eri3c's derivative records).

Every output element has one writing thread and every sum a fixed order, so the results are
bitwise reproducible run to run. Sources are C-style CUDA in the CUDA/HIP common subset; the block
size is a compile-time constant (NT threads), the warp size comes from the device
(LINUS_WARP_SIZE, the shuffle through portable.h's linus_shfl_down).

Device data: per primitive [p, Px, Py, Pz] (degree L's primitives back to back), h and A rows of
nherm(L) (nherm(L + 1) for A of the derivative kernels) per primitive; per point
[x, y, z, zeta^2, zeta] (zeta^2 = 0 marks a point charge) and the charges q.

CLI (through intgen.py):
    intgen.py pcm            writes crates/linus-gpu/src/kernels/pcm_gen/
    intgen.py --check pcm    compares instead of writing
"""
import pathlib

from cuda_common import CPrinter, boys_stage, lit
from ir import Graph, r_graph
from mdmath import BOYS_TMAX, herm_idx, herm_tuv, nherm

MAX_L = 8             # la + lb with orbital l <= 4
NT = 128              # threads per block (one pair primitive each)
TE = 32               # points per shared-memory tile, potential kernels
TD = 32               # points per tile, derivative kernels
RULE = "first"        # direction rule of the R recursion (mdmath.r_direction)
GEN_DIR = "crates/linus-gpu/src/kernels/pcm_gen"
CU_HEADER = "// @generated by tools/intgen/intgen.py pcm -- do not edit by hand."
TWO_PI = 6.283185307179586


def r_nodes(lt):
    """The IR of R_h for every Hermite index h of degree <= lt from s_n = R^(n)_000 and
    (px, py, pz) = P - r_g: (graph, nodes, [node of R_h in Hermite order])."""
    g = Graph(fold=True)
    xyz = [g.inp("px"), g.inp("py"), g.inp("pz")]
    _, nodes = r_graph(g, lt, RULE, lambda n: g.inp(f"s{n}"), xyz)
    return g, nodes, [nodes[(0,) + tuple(t)] for t in herm_tuv(lt)]


def r_stmts(nodes, pr, ind):
    """`const double` statements of the R nodes, level by level (the graph is already reduced to
    what the level-0 targets need)."""
    o = []
    for key, node in nodes.items():
        if node.op in ("in", "const") or node.id in pr.names:
            continue
        name = "r{}_{}_{}_{}".format(*key)
        o.append(f"{ind}const double {name} = {pr.defn(node)};")
        pr.bind(node, name)
    return o


def boys_point(lt, ind):
    """Statements giving s_0..s_lt = pref (-2 alpha)^n F_n(alpha |P - r_g|^2) for the point in
    `sj` (a Gaussian charge, or a point charge when zeta^2 = 0), with p, ipref = 2 pi / p, rr in
    scope. The Boys scheme of linus-ints' eri3c (table, Taylor sum, downward recursion; asymptotic
    form beyond BOYS_TMAX), as the generated eri3c kernels (cuda_common.boys_stage)."""
    prologue = ["double al = p, pref = ipref;",
                "if (sj[3] > 0.0) {",
                "    // Gaussian charge: alpha = p zeta^2 / (p + zeta^2), pref (2 pi / p) sqrt(alpha / p)",
                "    const double rs = rsqrt(p + sj[3]);",
                "    al = p * sj[3] * (rs * rs);",
                "    pref = ipref * sj[4] * rs;",
                "}"]
    return boys_stage(lt, ind, prologue, BOYS_TMAX)


def head(name, what, args):
    return [CU_HEADER,
            f"// {what}",
            f"extern \"C\" __global__ void __launch_bounds__({NT}) {name}(",
            f"    {args})",
            "{"]


def tile_load(ts, ind):
    """The point tile g0..g0 + ng (within the chunk, before gend) into shared memory:
    [x, y, z, zeta^2, zeta, q] per point."""
    return [f"{ind}const int ng = (int)(gend - g0 < {ts} ? gend - g0 : {ts});",
            f"{ind}__syncthreads();",
            f"{ind}for (int x = tid; x < 6 * ng; x += {NT}) {{",
            f"{ind}    const int j = x / 6, c = x - 6 * j;",
            f"{ind}    sp[x] = c < 5 ? pts[5 * (g0 + j) + c] : (q != 0 ? q[g0 + j] : 0.0);",
            f"{ind}}}",
            f"{ind}__syncthreads();"]


WARP_SUM = "{ind}for (int o = LINUS_WARP_SIZE / 2; o > 0; o >>= 1) {v} += linus_shfl_down({v}, o);"

CHUNK = ["    const long long gbeg = (long long)blockIdx.y * chunk;",
         "    const long long gend = npts < gbeg + chunk ? npts : gbeg + chunk;"]
NWARP = f"({NT} / LINUS_WARP_SIZE)"


def emit_e(L):
    """pcm_e{L}: potentials at the points (want_v) and Hermite accumulators of the charges
    (want_m) of the degree-L pair primitives (see the module docs)."""
    nh = nherm(L)
    g, nodes, R = r_nodes(L)
    pr = CPrinter()
    args = ("long long nprim, const double *__restrict__ prim, const double *__restrict__ hd,\n"
            "    double *__restrict__ acc, long long npts, long long chunk, const double *__restrict__ pts,\n"
            "    const double *__restrict__ q, const double *__restrict__ btab,\n"
            "    double *__restrict__ vpart, long long vblock0, int want_v, int want_m")
    o = head(f"pcm_e{L}", f"PCM potentials and charge accumulators, Hermite degree {L} ({nh} R values)", args)
    o += [f"    __shared__ double sp[{TE} * 6];",
          f"    __shared__ double sw[{NWARP} * {TE}];",
          "    const int tid = threadIdx.x;",
          "    const int lane = tid % LINUS_WARP_SIZE, warp = tid / LINUS_WARP_SIZE;",
          f"    const long long ip = (long long)blockIdx.x * {NT} + tid;",
          "    const bool act = ip < nprim;",
          "    double p = 1.0, cx = 0.0, cy = 0.0, cz = 0.0;",
          "    if (act) {",
          "        p = prim[4 * ip];",
          "        cx = prim[4 * ip + 1];",
          "        cy = prim[4 * ip + 2];",
          "        cz = prim[4 * ip + 3];",
          "    }",
          f"    const double ipref = {lit(TWO_PI)} / p;",
          "    const bool hv = act && want_v;",
          "    const double *hp = hd + " + f"{nh} * (hv ? ip : 0);"]
    for t in range(nh):
        o.append(f"    const double h{t} = hv ? hp[{t}] : 0.0;")
    o.append("    double " + ", ".join(f"a{t} = 0.0" for t in range(nh)) + ";")
    o += CHUNK
    o.append(f"    for (long long g0 = gbeg; g0 < gend; g0 += {TE}) {{")
    o += tile_load(TE, "        ")
    o += ["        for (int j = 0; j < ng; ++j) {",
          "            double v = 0.0;",
          "            if (act) {",
          "                const double *sj = sp + 6 * j;",
          "                const double px = cx - sj[0], py = cy - sj[1], pz = cz - sj[2];",
          "                const double rr = px * px + py * py + pz * pz;"]
    o += boys_point(L, "                ")
    o += r_stmts(nodes, pr, "                ")
    o.append("                if (want_v) {")
    o.append(f"                    v = h0 * {pr.ref(R[0])};")
    for t in range(1, nh):
        o.append(f"                    v = fma(h{t}, {pr.ref(R[t])}, v);")
    o.append("                }")
    o.append("                if (want_m) {")
    o.append("                    const double qj = sj[5];")
    for t in range(nh):
        o.append(f"                    a{t} = fma(qj, {pr.ref(R[t])}, a{t});")
    o.append("                }")
    o += ["            }",
          "            if (want_v) {",
          "                // the warp's share, a fixed shuffle tree",
          WARP_SUM.format(ind="                ", v="v"),
          f"                if (lane == 0) sw[warp * {TE} + j] = v;",
          "            }",
          "        }",
          "        __syncthreads();",
          "        if (want_v && tid < ng) {",
          "            // the block's share of the potential at point g0 + tid, warps in order",
          "            double s = 0.0;",
          f"            for (int w = 0; w < {NWARP}; ++w) s += sw[w * {TE} + tid];",
          "            vpart[(vblock0 + blockIdx.x) * npts + g0 + tid] = s;",
          "        }",
          "    }",
          "    if (act && want_m) {",
          f"        double *ap = acc + {nh} * ((long long)blockIdx.y * nprim + ip);"]
    for t in range(nh):
        o.append(f"        ap[{t}] = a{t};")
    o += ["    }", "}"]
    return "\n".join(o) + "\n"


def emit_d(L):
    """pcm_d{L}: the derivative terms of the degree-L pair primitives (see the module docs)."""
    nh0, nh1 = nherm(L), nherm(L + 1)
    g, nodes, R = r_nodes(L + 1)
    pr = CPrinter()
    tuv0 = herm_tuv(L)
    args = ("long long nprim, const double *__restrict__ prim, const double *__restrict__ hd,\n"
            "    double *__restrict__ acc, long long npts, long long chunk, const double *__restrict__ pts,\n"
            "    const double *__restrict__ q, const double *__restrict__ btab,\n"
            "    double *__restrict__ cpart, long long cblock0")
    o = head(f"pcm_d{L}", f"PCM first derivatives, Hermite degree {L} (R to degree {L + 1}, {nh1} values)", args)
    o += [f"    __shared__ double sp[{TD} * 6];",
          f"    __shared__ double sw[3 * {NWARP} * {TD}];",
          "    const int tid = threadIdx.x;",
          "    const int lane = tid % LINUS_WARP_SIZE, warp = tid / LINUS_WARP_SIZE;",
          f"    const long long ip = (long long)blockIdx.x * {NT} + tid;",
          "    const bool act = ip < nprim;",
          "    double p = 1.0, cx = 0.0, cy = 0.0, cz = 0.0;",
          "    if (act) {",
          "        p = prim[4 * ip];",
          "        cx = prim[4 * ip + 1];",
          "        cy = prim[4 * ip + 2];",
          "        cz = prim[4 * ip + 3];",
          "    }",
          f"    const double ipref = {lit(TWO_PI)} / p;",
          f"    const double *hp = hd + {nh0} * (act ? ip : 0);"]
    for t in range(nh0):
        o.append(f"    const double h{t} = act ? hp[{t}] : 0.0;")
    o.append("    double " + ", ".join(f"a{t} = 0.0" for t in range(nh1)) + ";")
    o += CHUNK
    o.append(f"    for (long long g0 = gbeg; g0 < gend; g0 += {TD}) {{")
    o += tile_load(TD, "        ")
    o += ["        for (int j = 0; j < ng; ++j) {",
          "            double c0 = 0.0, c1 = 0.0, c2 = 0.0;",
          "            if (act) {",
          "                const double *sj = sp + 6 * j;",
          "                const double px = cx - sj[0], py = cy - sj[1], pz = cz - sj[2];",
          "                const double rr = px * px + py * py + pz * pz;"]
    o += boys_point(L + 1, "                ")
    o += r_stmts(nodes, pr, "                ")
    for k in range(3):
        terms = []
        for t, (a, b, c) in enumerate(tuv0):
            s = [a, b, c]
            s[k] += 1
            terms.append((t, herm_idx(*s)))
        o.append(f"                c{k} = h{terms[0][0]} * {pr.ref(R[terms[0][1]])};")
        for t, r in terms[1:]:
            o.append(f"                c{k} = fma(h{t}, {pr.ref(R[r])}, c{k});")
    o.append("                const double qj = sj[5];")
    for t in range(nh1):
        o.append(f"                a{t} = fma(qj, {pr.ref(R[t])}, a{t});")
    o += ["            }",
          "            // the warp's shares, fixed shuffle trees",
          WARP_SUM.format(ind="            ", v="c0"),
          WARP_SUM.format(ind="            ", v="c1"),
          WARP_SUM.format(ind="            ", v="c2"),
          "            if (lane == 0) {",
          f"                sw[(0 * {NWARP} + warp) * {TD} + j] = c0;",
          f"                sw[(1 * {NWARP} + warp) * {TD} + j] = c1;",
          f"                sw[(2 * {NWARP} + warp) * {TD} + j] = c2;",
          "            }",
          "        }",
          "        __syncthreads();",
          f"        for (int x = tid; x < 3 * ng; x += {NT}) {{",
          "            // component k of the block's share at point g0 + j, warps in order",
          "            const int k = x / ng, j = x - k * ng;",
          "            double s = 0.0;",
          f"            for (int w = 0; w < {NWARP}; ++w) s += sw[(k * {NWARP} + w) * {TD} + j];",
          "            cpart[((cblock0 + blockIdx.x) * npts + g0 + j) * 3 + k] = s;",
          "        }",
          "    }",
          "    if (act) {",
          f"        double *ap = acc + {nh1} * ((long long)blockIdx.y * nprim + ip);"]
    for t in range(nh1):
        o.append(f"        ap[{t}] = a{t};")
    o += ["    }", "}"]
    return "\n".join(o) + "\n"


def gen_rust_tables():
    """crates/linus-gpu/src/kernels/pcm_gen/mod.rs: per degree the two kernel sources and their
    launch constants."""
    o = [CU_HEADER.replace("//", "//", 1),
         "//! Generated PCM surface-charge kernels (tools/intgen/cuda_pcm.py): per Hermite degree",
         "//! L = la + lb of the orbital pair, `pcm_e{L}` (potentials at the points and the charges'",
         "//! Hermite accumulators) and `pcm_d{L}` (first derivatives). One thread per pair primitive,",
         "//! `THREADS` per block; the points in shared-memory tiles of `TILE_E` and `TILE_D`.",
         "#![allow(clippy::all)]",
         "",
         f"/// Highest Hermite degree (orbital l <= 4).",
         f"pub const MAX_L: usize = {MAX_L};",
         f"/// Threads per block (one pair primitive each).",
         f"pub const THREADS: u32 = {NT};",
         f"/// Points per tile of the potential and the derivative kernels.",
         f"pub const TILE_E: usize = {TE};",
         f"pub const TILE_D: usize = {TD};",
         "",
         "/// `pcm_e{L}` sources, L = 0..=MAX_L.",
         f"pub static POTENTIAL: [&str; {MAX_L + 1}] = ["]
    for L in range(MAX_L + 1):
        o.append(f"    include_str!(\"e{L}.cu\"),")
    o.append("];")
    o.append("")
    o.append("/// `pcm_d{L}` sources, L = 0..=MAX_L.")
    o.append(f"pub static DERIVATIVE: [&str; {MAX_L + 1}] = [")
    for L in range(MAX_L + 1):
        o.append(f"    include_str!(\"d{L}.cu\"),")
    o.append("];")
    return "\n".join(o) + "\n"


def production(root):
    gen = pathlib.Path(root) / GEN_DIR
    files = {}
    for L in range(MAX_L + 1):
        files[gen / f"e{L}.cu"] = emit_e(L)
        files[gen / f"d{L}.cu"] = emit_d(L)
    files[gen / "mod.rs"] = gen_rust_tables()
    return files


def add_cli(sub):
    sub.add_parser("pcm", help="the linus-gpu PCM surface-charge kernels")


def run_cli(args, root):
    return production(root)
