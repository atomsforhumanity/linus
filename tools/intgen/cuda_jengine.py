"""CUDA emitter (layer c): the Hermite J-engine contractions of linus-gpu's density-fitted Coulomb
terms in Hermite space (crates/linus-gpu/src/jengine.rs: the J-only DF gradient and the memory-lean
DF-J), McMurchie-Davidson in Hermite space.

For a bra primitive (exponent p, centre P) and a ket primitive (q, Q) with the ket's Hermite
density h_u,

    A_t += sum_u (-1)^|u| h_u (Lambda_t^p | Lambda_u^q)
         = 2 pi^5/2 / (p q sqrt(p + q)) sum_u (-1)^|u| h_u R_{t+u}(alpha, P - Q),
    alpha = p q / (p + q).

Bras and kets are orbital pair primitives (Hermite degree la + lb, the bra's accumulators one
degree higher for the gradient's derivatives) or auxiliary primitives (an auxiliary solid harmonic
of degree l with exponent a is (2a)^-l sum_c S[c] Lambda_c, Hermite Gaussians of degree exactly l).
Only the degrees matter: `jengk_{B}_{K}` serves bras whose accumulators run over the Hermite indices
of degree <= B against auxiliary kets whose densities have degree exactly K; `jengb_{B}_{K}` bras of
degree exactly B (auxiliary) against pair kets of degree <= K; `jengbk_{B}_{K}` both exact. No work
goes to Hermite indices that carry nothing.

Mapping: one thread per bra primitive, a grid of (blocks of NT bra primitives) x (chunks of the
ket primitives); a thread loops over its chunk's kets in shared-memory tiles ([q, Qx, Qy, Qz,
bound, 1/q, h_0 .. h_{n-1}] per ket). Per (bra, ket): skipped unless bound_bra bound_ket >=
thresh (Cauchy-Schwarz over Hermite functions; the density-fitted passes give zero bounds and
thresh 0: nothing is skipped); then Boys F_0..F_{B+K} (the table scheme of the eri3c kernels
below T*, the asymptotic form from T* on: T* is where the asymptotic form of F_{B+K} is exact to
1e-17 relative, 37 for F_0 up to 78 for F_16, against the table's 117), the R recursion
(straight-line, every index t + u the contraction uses) and A_t = fma(+-h_u, R_{t+u}, A_t) in a
fixed order. Each thread writes its accumulators once per chunk (`acc[(chunk nbra + i) nb + t]`);
the host sums the chunks in a fixed order. Every result is bitwise reproducible run to run.

CLI (through intgen.py):
    intgen.py jengine            writes crates/linus-gpu/src/kernels/jengine_gen/
    intgen.py --check jengine    compares instead of writing
"""
import pathlib

from cuda_common import CPrinter, boys_stage, boys_tstar, lit
from ir import Graph, r_graph
from mdmath import herm_idx, herm_tuv, nherm

# orbital pairs up to f f (degree 6, + 1 for the gradient's derivatives) and auxiliary shells up
# to g (l = 4, + 1)
MAX_PAIR = 6
MAX_AUX = 4
# (variant, bra exact, ket exact, bra degrees, ket degrees)
VARIANTS = (
    ("jengk", False, True, MAX_PAIR + 1, MAX_AUX),  # orbital pair bra, auxiliary kets
    ("jengb", True, False, MAX_AUX + 1, MAX_PAIR),  # auxiliary bra, orbital pair kets
    ("jengbk", True, True, MAX_AUX + 1, MAX_AUX),   # auxiliary bra, auxiliary kets
)
NT = 128              # threads per block (one bra primitive each)
TILE_BYTES = 24576    # shared memory of a ket tile
RULE = "first"        # direction rule of the R recursion (mdmath.r_direction)
GEN_DIR = "crates/linus-gpu/src/kernels/jengine_gen"
CU_HEADER = "// @generated by tools/intgen/intgen.py jengine -- do not edit by hand."
ERI_PREF = 34.986836655249725   # 2 pi^5/2


def herm_set(l, exact):
    """The Hermite indices of degree <= l, or of degree exactly l."""
    return [t for t in herm_tuv(l) if not exact or sum(t) == l]


def tile(nk):
    """Kets per shared-memory tile for nk density values per ket, and the doubles per ket."""
    w = 6 + nk
    return max(8, min(64, TILE_BYTES // (8 * w)) // 8 * 8), w


def boys(lt, ind):
    """Statements giving s_n = pref (-2 alpha)^n F_n(alpha |P - Q|^2), n = 0..lt, for the ket in
    `sj` with p, ipref = ERI_PREF / p, rr in scope (the eri3c kernels' Boys scheme,
    cuda_common.boys_stage, with the asymptotic form from boys_tstar(lt) on, by rsqrt)."""
    prologue = ["const double q = sj[0];",
                "const double rs = rsqrt(p + q);",
                "const double al = p * q * (rs * rs);",
                "const double pref = ipref * rs * sj[5];"]
    return boys_stage(lt, ind, prologue, boys_tstar(lt), asym="rsqrt")


def emit(b, k, var, bx, kx):
    """{var}_{b}_{k}: the bra accumulators of degree <= b (exactly b with bx) against the kets
    of degree k (densities of degree exactly k with kx)."""
    lt = b + k
    tb, tk_ = herm_set(b, bx), herm_set(k, kx)
    nb, nk = len(tb), len(tk_)
    tk, w = tile(nk)
    g = Graph(fold=True)
    xyz = [g.inp("px"), g.inp("py"), g.inp("pz")]
    targets = sorted({(t[0] + u[0], t[1] + u[1], t[2] + u[2]) for t in tb for u in tk_},
                     key=lambda x: herm_idx(*x))
    _, nodes = r_graph(g, lt, RULE, lambda n: g.inp(f"s{n}"), xyz, targets=targets)
    pr = CPrinter()
    name = f"{var}_{b}_{k}"
    what = lambda l, x, n: f"degree {'' if x else '<= '}{l} ({n})"
    o = [CU_HEADER,
         f"// J-engine accumulators of Hermite {what(b, bx, nb)} against kets of {what(k, kx, nk)}",
         f"extern \"C\" __global__ void __launch_bounds__({NT}) {name}(",
         "    long long nbra, const double *__restrict__ bra, const double *__restrict__ bbnd,",
         "    long long nket, long long chunk, const int *__restrict__ kidx,",
         "    const double *__restrict__ ket, const double *__restrict__ kh,",
         "    const double *__restrict__ kbnd, const double *__restrict__ btab, double thresh,",
         "    double *__restrict__ acc)",
         "{",
         f"    __shared__ double sk[{tk} * {w}];",
         "    const int tid = threadIdx.x;",
         f"    const long long ip = (long long)blockIdx.x * {NT} + tid;",
         "    const bool act = ip < nbra;",
         "    double p = 1.0, cx = 0.0, cy = 0.0, cz = 0.0, bb = 0.0;",
         "    if (act) {",
         "        p = bra[4 * ip];",
         "        cx = bra[4 * ip + 1];",
         "        cy = bra[4 * ip + 2];",
         "        cz = bra[4 * ip + 3];",
         "        bb = bbnd[ip];",
         "    }",
         f"    const double ipref = {lit(ERI_PREF)} / p;",
         "    double " + ", ".join(f"a{t} = 0.0" for t in range(nb)) + ";",
         "    const long long gbeg = (long long)blockIdx.y * chunk;",
         "    const long long gend = nket < gbeg + chunk ? nket : gbeg + chunk;",
         f"    for (long long g0 = gbeg; g0 < gend; g0 += {tk}) {{",
         f"        const int ng = (int)(gend - g0 < {tk} ? gend - g0 : {tk});",
         "        __syncthreads();",
         f"        for (int x = tid; x < {w} * ng; x += {NT}) {{",
         f"            const int j = x / {w}, c = x - {w} * j;",
         "            const long long kk = kidx[g0 + j];",
         f"            sk[x] = c < 4 ? ket[4 * kk + c] : (c == 4 ? kbnd[kk] : (c == 5 ? 1.0 / ket[4 * kk] : kh[{nk} * kk + c - 6]));",
         "        }",
         "        __syncthreads();",
         "        for (int j = 0; j < ng; ++j) {",
         f"            const double *sj = sk + {w} * j;",
         "            if (!(bb * sj[4] >= thresh)) continue;",
         "            const double px = cx - sj[1], py = cy - sj[2], pz = cz - sj[3];",
         "            const double rr = px * px + py * py + pz * pz;"]
    ind = "            "
    o += boys(lt, ind)
    for key, node in nodes.items():
        if node.op in ("in", "const") or node.id in pr.names:
            continue
        nm = "r{}_{}_{}_{}".format(*key)
        o.append(f"{ind}const double {nm} = {pr.defn(node)};")
        pr.bind(node, nm)
    for u in range(nk):
        o.append(f"{ind}const double h{u} = sj[{6 + u}];")
    # A_t = sum_u (-1)^|u| h_u R_{t+u}, u in Hermite order for every t
    for ti, t in enumerate(tb):
        for ui, u in enumerate(tk_):
            r = pr.ref(nodes[(0, t[0] + u[0], t[1] + u[1], t[2] + u[2])])
            hs = f"h{ui}" if sum(u) % 2 == 0 else f"-h{ui}"
            o.append(f"{ind}a{ti} = fma({hs}, {r}, a{ti});")
    o += ["        }",
          "    }",
          "    if (act) {",
          f"        double *ap = acc + {nb} * ((long long)blockIdx.y * nbra + ip);"]
    for t in range(nb):
        o.append(f"        ap[{t}] = a{t};")
    o += ["    }", "}"]
    return "\n".join(o) + "\n"


def gen_rust_tables():
    """crates/linus-gpu/src/kernels/jengine_gen/mod.rs: the kernel sources and launch constants."""
    o = [CU_HEADER,
         "//! Generated J-engine kernels (tools/intgen/cuda_jengine.py) of the density-fitted Coulomb",
         "//! terms in Hermite space: `{variant}_{B}_{K}`, the Hermite accumulators of degree <= B",
         "//! (exactly B: `jengb`, `jengbk`) of the bra primitives against the ket primitives of degree K",
         "//! with their Hermite densities (of degree exactly K: `jengk`, `jengbk`). One thread per bra",
         "//! primitive, `THREADS` per block; the kets in shared-memory tiles (`Variant::tile`).",
         "#![allow(clippy::all)]",
         "",
         "/// Highest orbital pair degree (orbital l <= 3).",
         f"pub const MAX_PAIR: usize = {MAX_PAIR};",
         "/// Highest auxiliary degree (l <= 4).",
         f"pub const MAX_AUX: usize = {MAX_AUX};",
         "/// Threads per block (one bra primitive each).",
         f"pub const THREADS: u32 = {NT};",
         "",
         "/// A kernel family: its entry prefix, bra and ket degree ranges, ket tiles and sources",
         "/// (index b (kmax + 1) + k).",
         "pub struct Variant {",
         "    pub name: &'static str,",
         "    pub bmax: usize,",
         "    pub kmax: usize,",
         "    pub tiles: &'static [usize],",
         "    pub sources: &'static [&'static str],",
         "}",
         "",
         "impl Variant {",
         "    /// The source of `{name}_{b}_{k}`.",
         "    pub fn source(&self, b: usize, k: usize) -> &'static str {",
         "        self.sources[b * (self.kmax + 1) + k]",
         "    }",
         "",
         "    /// Kets per tile at ket degree `k`.",
         "    pub fn tile(&self, k: usize) -> usize {",
         "        self.tiles[k]",
         "    }",
         "}",
         ""]
    for var, bx, kx, bmax, kmax in VARIANTS:
        nkk = lambda k: len(herm_set(k, kx))
        o.append(f"/// `{var}_{{B}}_{{K}}`, B <= {bmax}, K <= {kmax}.")
        o.append(f"pub static {var.upper()}: Variant = Variant {{")
        o.append(f"    name: \"{var}\",")
        o.append(f"    bmax: {bmax},")
        o.append(f"    kmax: {kmax},")
        o.append(f"    tiles: &[{', '.join(str(tile(nkk(k))[0]) for k in range(kmax + 1))}],")
        o.append("    sources: &[")
        for b in range(bmax + 1):
            for k in range(kmax + 1):
                o.append(f"        include_str!(\"{var}_{b}_{k}.cu\"),")
        o.append("    ],")
        o.append("};")
        o.append("")
    return "\n".join(o[:-1]) + "\n"


def production(root):
    gen = pathlib.Path(root) / GEN_DIR
    files = {}
    for var, bx, kx, bmax, kmax in VARIANTS:
        for b in range(bmax + 1):
            for k in range(kmax + 1):
                files[gen / f"{var}_{b}_{k}.cu"] = emit(b, k, var, bx, kx)
    files[gen / "mod.rs"] = gen_rust_tables()
    return files


def add_cli(sub):
    sub.add_parser("jengine", help="the linus-gpu J-engine kernels")


def run_cli(args, root):
    return production(root)
